def сноска(ид, цитата, подпись, источник):
    """Строка определения сноски в точности той формы, что печатает
    `articles._footnote_line` (подпись необязательна — у записей FAQ её нет)."""
    хвост = ("%s, " % подпись) if подпись else ""
    return "[^%s]: «%s» — %s[[%s]]" % (ид, цитата, хвост, источник)


def статья(тело, сноски=(("f1", Ц_ЗАЗОР, П_ЗАЗОР, S_ЗАЗОР),), фронт=ФМ, заголовок="Зазоры"):
    out = фронт + "# %s\n\n" % заголовок + тело.rstrip("\n") + "\n"
    if сноски:
        out += "\n## Сноски\n\n" + "\n".join(сноска(*с) for с in сноски) + "\n"
    return out


