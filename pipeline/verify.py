"""Последний рубеж фазы Ф3 (задача 6): проверяльщик готовой статьи.

Спека §8 называет его главным тестом проекта: проверяльщику, который не
ловит подделку, верить нельзя, поэтому его самого проверяют враньём
(`tests/test_verify.py`, `tests/подделки/`). Работает на уже СОБРАННОЙ
статье (`pipeline.articles.render`/`build`), а не на черновике — предыдущие
рубежи (гейт фактов `pipeline.facts`, запрет встроенной сноски
`pipeline.articles`) защищают процесс сборки; этот модуль исходит из того,
что процесс мог быть обойдён (статья подменена вручную, собрана старой
версией кода, испорчена при переносе) и сверяет РЕЗУЛЬТАТ заново, с нуля.

Своих цепочек резолва не заводит (Global Constraint фазы №3): ссылка на
заметку резолвится `check_mirror.build_notes_index`/`resolve_note`, а
дословность цитаты и цитируемость источника — `pipeline.facts.check_one`
(та же функция, что использует гейт прохода 1, включая
`notes.citable_source` — дубли FAQ и выдержки блогов). Это единственное
намеренное дублирование логики с `pipeline.articles`: подпись сноски
(автор/дата) сверяется НЕЗАВИСИМО, тем же строителем строки
(`articles._footnote_line`), но с автором/датой, взятыми заново из базы —
если бы этот модуль доверял подписи, уже стоящей в статье, вторая линия
обороны ничего не проверяла бы поверх первой.
"""
from __future__ import annotations

import re
import sqlite3
from pathlib import Path

from . import articles, check_mirror, facts, notes

# --- определения сносок в ГОТОВОЙ статье -------------------------------------
#
# Форма ЗАДАНА `articles._footnote_line` — не переизобретается: «маркер,
# двоеточие, «цитата» — [подпись,] [[источник]]». Подпись (автор, дата)
# необязательна (запись FAQ); источник — ВСЕГДА последняя вики-ссылка в
# строке. `.+` для цитаты жадный — если в самой цитате когда-нибудь
# встретится «» — [[», это по-прежнему разберётся верно (жадность берёт
# ПОСЛЕДНЕЕ вхождение разделителя в строке).
_FOOTNOTE_DEF = re.compile(r"^\[\^(?P<id>[^\]\s]+)\]:\s+«(?P<quote>.+)»\s+—\s+(?P<rest>.+)$", re.M)
_SOURCE_IN_REST = re.compile(r"\[\[([^\]]+)\]\]\s*$")


def _parse_footnote_definitions(body: str) -> tuple[dict[str, dict], list[str]]:
    """Определения сносок готовой статьи -> `{id: {"цитата", "источник",
    "строка"}}` + список проблем формата (ссылки нет вовсе, id повторён).

    `body` обязан быть УЖЕ пропущен через `articles._strip_non_prose` (Н3
    ре-ревью задачи 6): без этого определение, спрятанное в кодблоке,
    инлайн-коде или комментарии (`` ``` ``, `` ` ``, `<!-- -->`, `%%…%%`),
    попадает в `defs` как настоящее, хотя читатель в Obsidian такой сноски
    не увидит вовсе — асимметрия с `articles.used_ids` (та же зачистка уже
    применяется к маркерам, но не к определениям) и есть находка Н3.

    Не привязано к разделу «## Сноски» — сканирует ВЕСЬ текст: подделка
    вправе разместить поддельное определение где угодно, а не только в
    ожидаемом месте.
    """
    defs: dict[str, dict] = {}
    problems: list[str] = []
    for m in _FOOTNOTE_DEF.finditer(body):
        fid = m.group("id")
        rest = m.group("rest")
        src_m = _SOURCE_IN_REST.search(rest)
        if not src_m:
            problems.append("определение сноски [^%s] не содержит ссылки [[...]] на источник" % fid)
            continue
        if fid in defs:
            problems.append("определение сноски [^%s] встречается более одного раза" % fid)
            continue
        defs[fid] = {"цитата": m.group("quote"), "источник": src_m.group(1).strip(), "строка": m.group(0)}
    return defs, problems


# --- числа с единицами измерения ---------------------------------------------
#
# Извлечение чисел и канонизация единиц — `notes.find_number_units`, общая
# функция с `pipeline.facts` (потолок числа значений в одной цитате, Н11
# ре-ревью): числа с единицами измерения — самое опасное место техбазы для
# подмены, значит два потребителя одного правила обязаны ходить одной
# функцией (см. её докстринг про Н1 — список исключений, а не разрешённого).
#
# Здесь, в verify.py, задача другая — не РАСПОЗНАТЬ число с единицей (это
# уже умеет `find_number_units`), а разбить ГОТОВУЮ СТАТЬЮ на самостоятельные
# «утверждения», для каждого из которых есть СВОЙ набор маркеров: пункт
# списка, ячейка таблицы, строка заголовка, строка коллаута/цитаты и
# сегмент прозы между соседними маркерами — самостоятельные единицы
# проверки (находка Н2), а не «предложение» по точке (Н7 ре-ревью: русские
# сокращения «т. е.», «см.» рвут предложение на два, а маркер после точки
# — по Н2/Н7 корню, единица должна определяться позицией МАРКЕРА, а не
# пунктуацией).
_LIST_ITEM = re.compile(r"^\s*(?:[-*+]|\d+\.)\s+")
_HEADING_LINE = re.compile(r"^#{1,6}\s+")
_QUOTE_LINE = re.compile(r"^>+\s?")
_TABLE_ROW = re.compile(r"^\s*\|.*\|\s*$")
_TABLE_SEPARATOR = re.compile(r"^\s*\|?[\s:|-]+\|?\s*$")


def _blocks(text: str) -> list[tuple[str, bool]]:
    """Делит прозу на независимые «утверждения» по разметке, а не по
    абзацам-предложениям (Н2): пункт списка и СТРОКА таблицы — каждый
    самостоятелен (ложь в одной строке списка не должна прикрываться
    сноской из другой), заголовок и строка коллаута/цитаты — тоже не
    «не проза», как было раньше (`_sentences` до этой правки пропускала
    их целиком по префиксу `#`/`>`), а такая же проверяемая единица.
    Обычный абзац (в т.ч. перенесённый по строкам мягким переносом
    markdown) остаётся ОДНИМ блоком — дробит его дальше не пунктуация, а
    позиции маркеров (`_marker_segments`).

    Возвращает пары `(текст, atomic)`. `atomic=True` — ТОЛЬКО у строки
    таблицы (дефект 6, пилот статей Ф3): раньше единицей утверждения была
    ЯЧЕЙКА, а не строка, — «| при 20 градусах | 3,0 К Ом [^f7] |» дробилось
    на два независимых «утверждения», и ячейка «при 20 градусах» осталась
    БЕЗ маркера, хотя автор поставил его в СТРОКУ, просто в другую колонку
    той же строки (обе ячейки описывают ОДНО утверждение источника,
    разнесённое по столбцам таблицы — так человек и пишет такие строки).
    Число «20» без прикрывающего маркера отклонялось как «не встречается ни
    в одной сноске», хотя дословно стоит в цитате того же факта. Для
    строки-блока `check()` строит РОВНО ОДИН сегмент из ВСЕХ маркеров
    строки (а не через `_marker_segments`, который делит по позиции
    маркера — правильное правило для списка/прозы, но здесь дало бы то же
    расщепление ещё раз, просто внутри одной строки, если маркеров в ней
    больше одного) — маркер в любой ячейке покрывает числа во всех ячейках
    строки. Строка совсем без маркера всё равно становится сегментом
    (`marker_ids=[]`) — молчания без единой сноски это не открывает.

    Строка ЗАГОЛОВКА таблицы (первая до строки-разделителя `|---|---|`) и
    сама строка-разделитель — не факт источника, а имена колонок; в
    `out` не попадают вовсе (не становятся утверждением, которое обязано
    иметь сноску). `atomic=False` — у всех остальных видов (список,
    заголовок документа, цитата, обычный абзац): дробятся дальше позициями
    маркеров, как раньше — это НЕ то же самое послабление, что у таблицы,
    просто оно им не нужно: у списка/заголовка/цитаты нет родного «одно
    утверждение источника, разнесённое по нескольким типографским
    колонкам», которое есть только у строки таблицы.
    """
    out: list[tuple[str, bool]] = []
    for para in notes.PARAGRAPH_SPLIT.split(text):
        lines = [l for l in para.split("\n") if l.strip()]
        if not lines:
            continue
        if all(_TABLE_ROW.match(l) for l in lines):
            sep_idx = next((i for i, l in enumerate(lines) if _TABLE_SEPARATOR.match(l)), None)
            for i, line in enumerate(lines):
                if _TABLE_SEPARATOR.match(line):
                    continue
                if sep_idx is not None and i < sep_idx:
                    continue  # строка заголовка — имена колонок, не факт
                cells = [c.strip() for c in line.strip().strip("|").split("|")]
                row = " ".join(c for c in cells if c)
                if row:
                    out.append((row, True))
            continue
        if all(_LIST_ITEM.match(l) for l in lines):
            out.extend((_LIST_ITEM.sub("", l.strip()), False) for l in lines)
            continue
        if all(_HEADING_LINE.match(l) for l in lines):
            out.extend((_HEADING_LINE.sub("", l.strip()), False) for l in lines)
            continue
        if all(_QUOTE_LINE.match(l) for l in lines):
            out.extend((_QUOTE_LINE.sub("", l.strip()), False) for l in lines)
            continue
        out.append((" ".join(l.strip() for l in lines), False))
    return out


_MARKER = re.compile(r"\[\^([^\]\s]+)\]")


def _marker_segments(block: str) -> list[tuple[str, list[str]]]:
    """Делит `block` на сегменты по позициям маркеров: сегмент — от конца
    предыдущего маркера (или начала блока) до конца очередного маркера,
    плюс хвост после последнего маркера БЕЗ маркера вовсе. Так число,
    стоящее в блоке без единой сноски рядом (`C1`/`C2`.. ре-ревью — вторая
    половина списка/абзаца без своего маркера), не получает прикрытия от
    маркера, стоящего в другом месте того же блока — а маркер, поставленный
    ПОСЛЕ точки (`I3` ре-ревью — `«2 мм. [^f1]»`), не отрывается от числа,
    которое подтверждает: деление идёт по маркеру, а не по пунктуации.
    """
    segments: list[tuple[str, list[str]]] = []
    pos = 0
    for m in _MARKER.finditer(block):
        segments.append((block[pos:m.end()], [m.group(1)]))
        pos = m.end()
    tail = block[pos:]
    if tail.strip() or not segments:
        segments.append((tail, []))
    return segments


def check(article_path: Path, wiki_root: Path, mirror_root: Path, conn: sqlite3.Connection,
          verified: list[dict] | None = None) -> dict:
    """Проверяет готовую статью `article_path` против дерева `wiki_root` и
    базы `conn`. Возвращает `{"ок": bool, "проблемы": [...],
    "источники_без_цитаты": [...]}`.

    `wiki_root` и `mirror_root` — РАЗНЫЕ корни для разных вопросов (Н5
    ре-ревью задачи 6, тот же приём для Н12/Н13): «резолвится ли вообще
    ссылка/совпадает ли имя» спрашивается у ВСЕГО дерева вики (`wiki_root`,
    обычно `wiki/`, включая `Статьи/` — так же, как `check_mirror.check`
    проверяет вики целиком), а «можно ли процитировать» — только у
    `mirror_root` (обычно `wiki/Источники/`): статья не может быть
    архивным источником сама себе, сколько бы других статей рядом ни было.
    До этой правки `verify` резолвил ссылки ТОЛЬКО по `Источники/` — ссылка
    «смотри также» на другую статью считалась выдуманной (ложное
    срабатывание, живой пример ревью — `[[Расшифровка VIN Subaru]]`), а
    коллизия имени (2-бис) проверялась только против источников, не против
    других статей (`Зазоры клапанов` в `Двигатель/` и в `Ходовая/` — то же
    самое `[[Зазоры клапанов]]` неоднозначно, но проверка этого не видела).

    `источники_без_цитаты` — доля фактов, которые ИИ молча проигнорировал
    (спека §6): это МЕРА, не нарушение контракта (пропущенный, но честный
    факт — не ложь), поэтому не входит в `проблемы` и не сбивает `ок`.

    `verified` — список проверенных фактов (`articles/проверено/<ключ>.json`,
    поле `"проверено"`, выход `facts.check_all`), НЕОБЯЗАТЕЛЬНЫЙ, но если
    дан — включает Н6 ре-ревью задачи 6: без него `источники_без_цитаты`
    раньше просто ПЕРЕПЕЧАТЫВАЛ frontmatter `неиспользованные_факты` —
    поле, которое пишет `articles.render`, тот самый процесс, который
    докстринг модуля выше явно называет обходимым («мог быть обойдён»).
    Мера, взятая из процесса, который проверяется, — не мера. С `verified`
    под рукой модуль считает неиспользованные факты САМ (по разнице
    `{id фактов} - {использованные маркеры}`) и, вдобавок, сверяет два
    frontmatter-ПОЛЯ-ЗАЯВКИ («неиспользованные_факты», «источников») с
    реальным подсчётом — расхождение само по себе означает, что статья не
    соответствует тем фактам, которыми её якобы собрали, и это уже
    `проблема`, а не измерение.
    """
    article_path = Path(article_path)
    wiki_root = Path(wiki_root)
    mirror_root = Path(mirror_root)

    try:
        meta, raw_body = articles._parse_draft(article_path)
    except articles.DraftError as e:
        return {"ок": False, "проблемы": [str(e)], "источники_без_цитаты": []}

    # Н3 ре-ревью задачи 6: определение сноски, спрятанное в кодблоке,
    # инлайн-коде или комментарии (`` ``` ``/`` ` ``/`<!-- -->`/`%%…%%`),
    # раньше попадало в `defs` как настоящее — читатель в Obsidian такой
    # сноски не увидит вовсе (кодблок печатает её буквально, комментарий не
    # рендерится), а гейт говорил «ок». `articles._strip_non_prose` — та же
    # зачистка, что уже применяется к маркерам (`used_ids`); асимметрия
    # между двумя половинами ОДНОЙ проверки была самой находкой (Global
    # Constraint №3 запрещает ровно это, только оба потребителя тут — в
    # одном модуле). Зачищается ВЕСЬ текст статьи один раз, до разбора и
    # определений, и чисел, и ссылок — не только определений: маркер и
    # число в кодблоке (Н7, `I6`) читателю тоже не видны.
    body = articles._strip_non_prose(raw_body)

    problems: list[str] = []

    defs, def_problems = _parse_footnote_definitions(body)
    problems += def_problems

    # 1. Каждый маркер обязан иметь определение сноски, и наоборот —
    # определения ищутся отдельно от маркеров (`_FOOTNOTE_DEF.sub` вырезает
    # СТРОКИ определений целиком), иначе `[^f1]:` засчитал бы сам себя как
    # использование `[^f1]` в прозе, и проверка не могла бы поймать ничего.
    prose = _FOOTNOTE_DEF.sub("", body)
    used = set(articles.used_ids(prose))
    defined = set(defs)
    for fid in sorted(used - defined):
        problems.append("маркер [^%s] в тексте не имеет определения сноски" % fid)
    for fid in sorted(defined - used):
        problems.append("определение сноски [^%s] не используется ни одним маркером текста" % fid)

    # 2. Ссылка резолвится через check_mirror (готовый резолв, не своя
    # цепочка — Global Constraint фазы №3), ЯКОРЬ — тоже (Н4 ре-ревью: до
    # этой правки от ссылки в ПРОЗЕ бралась только цель, якорь
    # выбрасывался — битый/чужой/перекрёстный якорь у ссылки вне сноски
    # проходил молча, хотя `check_mirror.check` для заметок зеркала
    # ровно это умеет; `anchor_exists`/`build_heading_index`/
    # `build_block_index` — та же функция, вынесенная из `check()` этим же
    # ре-ревью), и ПО АЛИАСУ, не только по машинному имени (Н14: ссылка
    # «смотри также [[Провалы в работе ДВС]]» — человеческий alias темы,
    # `resolve_note` его не знает вовсе). Индекс строится по `wiki_root`
    # ЦЕЛИКОМ (Н5: раньше индекс строился только по `Источники/`, и ссылка
    # на другую статью, «смотри также [[Расшифровка VIN Subaru]]», считалась
    # выдуманной — ложное срабатывание). Сканирует ВЕСЬ текст, а не только
    # источники сносок: прозе ничто не мешает содержать ещё и
    # самостоятельные вики-ссылки, которые `facts.check_one` ниже никогда
    # не увидит (он получает только источники ИЗ определений).
    notes_index, by_name = check_mirror.build_notes_index(wiki_root)
    alias_index = check_mirror.build_alias_index(notes_index)
    headings = check_mirror.build_heading_index(notes_index)
    blocks = check_mirror.build_block_index(notes_index)

    # Сознательное решение (Н10 ре-ревью): ссылка «смотри также
    # [[Тема N]]» на ПУСТУЮ тему форума (без единого поста, контракт
    # зеркала §3) заметку резолвит и якорем не помечена — проходит эту
    # проверку. Контракт запрещает ЦИТИРОВАТЬ пустую тему как источник
    # (проверено живьём: любой якорь закрытого списка отвергается —
    # `notes.section` не находит ни одного заголовка), но не запрещает
    # НА НЕЁ ССЫЛАТЬСЯ как на указатель «тема существовала, вот её номер»
    # — сама заметка при этом реальна, ведёт в неё честно, и коллаут
    # «содержимое не сохранилось» читатель увидит сам, дойдя по ссылке.
    def _resolve_by_name_or_alias(target: str) -> list[str] | None:
        return (check_mirror.resolve_note(target, notes_index, by_name)
                or alias_index.get(target.casefold()))

    for target, anchor in check_mirror.LINK.findall(body):
        target = target.strip()
        if not target:
            continue
        resolved = _resolve_by_name_or_alias(target)
        if not resolved:
            problems.append("ссылка [[%s]] не резолвится ни в одну заметку зеркала" % target)
            continue
        if anchor and not check_mirror.anchor_exists(resolved, anchor[1:], headings, blocks):
            problems.append("ссылка [[%s%s]] — заметка есть, а якорь не найден" % (target, anchor))

    # 2-бис. Имя статьи (= её файл, `articles.build` пишет `<заголовок>.md`)
    # и её собственные алиасы (если появятся) НЕ совпадают с именем/алиасом
    # НИ ОДНОЙ другой заметки дерева — источника или другой статьи.
    # `check_mirror.check` никогда не увидит эту дыру: при полной сборке
    # вики (`Источники/` и `Статьи/` в ОДНОМ дереве, как их проверяет `run
    # check`) две заметки с одним и тем же именем в разных папках не
    # отвергаются, а СЛИВАЮТСЯ (якорь сверяется с объединением) — резолв по
    # имени (и сам Obsidian) в такой ситуации не различает их, и сноска
    # молча резолвится (в том числе) в СТАТЬЮ вместо архивного источника.
    #
    # Три обхода первой версии проверки, найденные ре-ревью:
    # - Н12 (регистр): Obsidian резолвит ссылки БЕЗ учёта регистра
    #   (`«тема 25570»`/`«ТЕМА 25570»` — то же имя), сравнение было точной
    #   строкой — `casefold()` здесь и в `by_name`/`alias_index` ниже;
    # - Н12/Н14 (alias-пространство): у заметок зеркала **машинное** имя
    #   файла (`Тема N`), но живой человек называет статью, скорее всего,
    #   так же, как названа тема форума (`aliases`, 6885 разных, 3432 годятся
    #   в заголовок статьи по живому замеру) — коллизия возможна ИМЕННО
    #   там, а не в пространстве машинных имён, которое проверялось раньше;
    # - Н13 (статья vs статья): проверка смотрела только в `Источники/`;
    #   `wiki_root` целиком закрывает и этот случай тем же кодом.
    #
    # Собственный ключ статьи (если она уже лежит внутри `wiki_root`)
    # исключается из совпадений — иначе она была бы «коллизией» сама с
    # собой при каждом прогоне уже опубликованной статьи.
    own_key = None
    try:
        own_key = article_path.resolve().relative_to(wiki_root.resolve()).with_suffix("").as_posix()
    except ValueError:
        pass

    # `title_collisions` — общая функция с `pipeline.articles.build` (первый
    # рубеж, до записи файла), не переизобретённая здесь копия того же
    # алгоритма; см. её докстринг про то, почему коллизия — рутинный, а не
    # краевой случай.
    for name in [article_path.stem] + list(meta.get("aliases", [])):
        collisions = check_mirror.title_collisions(name, by_name, alias_index, own_key=own_key)
        if collisions:
            problems.append(
                "имя статьи «%s» совпадает с именем/алиасом заметки «%s» в зеркале — ссылка на "
                "этот адрес станет неоднозначной и может молча резолвиться не туда"
                % (name, ", ".join(collisions)))

    # 3-4. Дословность цитаты, цитируемость источника (дубль FAQ/выдержка
    # блога — `notes.citable_source` изнутри `check_one`) и «цитата не из
    # генератора» — всё это уже умеет `facts.check_one`, вызывать заново не
    # нужно (Global Constraint №3 плюс явное указание брифа: дословность
    # берём у `facts.check_one`, своей не пишем).
    #
    # Подпись (автор/дата) сверяется НЕЗАВИСИМО и только для тех сносок,
    # что прошли `check_one`: если цитата уже подделана, о подписи сообщать
    # избыточно и запутывает причину отказа.
    for fid, info in sorted(defs.items()):
        ok, reason = facts.check_one({"источник": info["источник"], "цитата": info["цитата"]},
                                      mirror_root, conn)
        if not ok:
            problems.append("сноска [^%s]: %s" % (fid, reason))
            continue

        author, when = facts._lookup_meta(info["источник"], conn)
        expected = articles._footnote_line({
            "id": fid, "источник": info["источник"], "цитата": info["цитата"],
            "автор": author, "дата": when,
        })
        if expected != info["строка"]:
            problems.append(
                "сноска [^%s]: подпись и/или ссылка не совпадают с тем, что база знает про "
                "источник (ожидалось «%s», в статье «%s»)" % (fid, expected, info["строка"]))

    # 5. Каждое число с единицей измерения в УТВЕРЖДЕНИИ обязано найтись
    # хотя бы в одной сноске ЭТОГО утверждения — подмену цифр (самое
    # опасное для техбазы) не ловит ничего из проверок выше: и дословная
    # цитата, и подпись могут быть настоящими у СОСЕДНЕГО факта, который
    # просто оказался рядом с искажённым числом. «Утверждение» — пункт
    # списка, ячейка таблицы, строка заголовка/коллаута или сегмент прозы
    # между соседними маркерами (`_blocks`/`_marker_segments`, Н2/Н7
    # ре-ревью) — независимо от разметки, а не абзац, разрезанный по точке.
    #
    # Сознательная граница (Н7 ре-ревью, находка I4): честный ПЕРЕСЧЁТ
    # единицы автором статьи («зазор 2 мм (0,2 см)») тоже отклоняется —
    # «0,2 см» дословно в сноске не стоит, откуда бы она ни бралась
    # арифметикой. По букве брифа («каждое число с единицей... встречается
    # хотя бы в одной сноске») это верно, и держать это строгим безопаснее,
    # чем учить проверяльщик арифметике конверсий единиц (сама конверсия —
    # ещё один способ ошибиться, который потом придётся проверять отдельно).
    # Обходной путь у автора статьи есть: включить пересчитанное значение
    # прямо в цитату факта на проходе 1, а не только в прозу.
    #
    # Н16 ре-ревью: исключение (год/лет/раз/шт/месяц/человек/деньги — не
    # единица измерения) само стало лазейкой в первой версии — число, за
    # которым стоит исключённое слово, не проверялось НИКАК, и подмена года
    # выпуска («8-й символ... 1998 год» при источнике «(С-1992)») проходила
    # бы молча. `notes.find_quantity_claims` не требует слова «единицы»
    # рядом (в цитате источника его может и не быть — «(С-1992)», а не
    # «1992 год») — сверяется голое число.
    for block, atomic in _blocks(prose):
        # Строка таблицы (`atomic=True`) — ОДИН сегмент из ВСЕХ маркеров
        # блока целиком (дефект 6): маркер в любой ячейке покрывает числа
        # во всех ячейках строки, а не только «после себя» по позиции, как
        # у `_marker_segments` (см. докстринг `_blocks`).
        segments = [(block, _MARKER.findall(block))] if atomic else _marker_segments(block)
        for segment, marker_ids in segments:
            quotes = [defs[fid]["цитата"] for fid in marker_ids if fid in defs]

            occurrences = notes.find_number_units(segment)
            if occurrences:
                covered: set[tuple[str, str]] = set()
                for q in quotes:
                    covered |= notes.find_number_units(q)
                missing = occurrences - covered
                # Дефект 9 (пилот статей, живая находка): «при 20 градусах
                # он должен выдавать 3,0 К Ом, при 50 - 0,7-1,0 К Ом» —
                # автор источника не повторяет «градусах» у второго члена
                # перечисления через запятую (обычная русская элизия), а
                # статья восстанавливает её («при 50 градусах») для
                # читаемости таблицы. Число «50» и единица «градусах»
                # существуют в цитате ОТДЕЛЬНО (число голым, единица — при
                # ДРУГИХ числах, 20 и 80), просто не рядом друг с другом в
                # ЭТОМ месте цитаты.
                #
                # Правило узкое и безопасное с обеих сторон: пара считается
                # найденной, только если ОБА условия выполнены — голое
                # число есть в цитате (`find_bare_numbers`, защита от
                # VIN/артикула та же, что и везде) И единица уже встречена
                # в цитате хотя бы при ОДНОМ числе (значит это не
                # выдуманная величина, а настоящая единица этого текста).
                # Подмену числа продолжает ловить первое условие (голого
                # числа не найдётся вовсе); подмену единицы — второе
                # (единица, которой в цитате нет НИ ПРИ ОДНОМ числе,
                # покрытием не считается). Не путать со «вторым» живым
                # случаем той же фазы («на сотню» вместо «100 км») — там
                # число целиком отсутствует в цитате (сотня — слово, не
                # цифра), первое условие не выполняется, и это правило его
                # не закрывает (сознательно — см. отчёт).
                if missing:
                    covered_units = {u for _n, u in covered}
                    bare_in_quotes: set[str] = set()
                    for q in quotes:
                        bare_in_quotes |= notes.find_bare_numbers(q)
                    for num, unit in sorted(missing):
                        if unit in covered_units and num in bare_in_quotes:
                            continue
                        problems.append(
                            "число «%s %s» в утверждении «%s» не встречается ни в одной сноске "
                            "этого утверждения" % (num, unit, segment.strip()))

            claims = notes.find_quantity_claims(segment)
            if claims:
                # Сторона ИСТОЧНИКА — `find_bare_numbers`, не `find_
                # quantity_claims`: слова «год»/«раз» рядом с числом в
                # ЦИТАТЕ может и не быть вовсе (контракт зеркала §1: «8 -
                # Год выпуска (С-1992)» — год выпуска внутри скобок, без
                # единого слова «год» рядом). Проверяется голое число.
                covered_claims: set[str] = set()
                for q in quotes:
                    covered_claims |= notes.find_bare_numbers(q)
                for num in sorted(claims - covered_claims):
                    problems.append(
                        "число «%s» в утверждении «%s» не встречается ни в одной сноске этого "
                        "утверждения (год/срок/количество — тоже проверяемый факт, не только "
                        "единица измерения)" % (num, segment.strip()))

    # 6. Источники, не процитированные ни разу — СЧИТАЕТСЯ ЗАНОВО по
    # `verified` (Н6 ре-ревью), а не перепечатывается из frontmatter.
    # Заодно сверяются два поля-ЗАЯВКИ, которые пишет `articles.render`
    # («неиспользованные_факты», «источников») — расхождение с реальным
    # подсчётом означает, что статья не соответствует фактам, которыми её
    # якобы собрали (задача 5 отдельно чинила завышение «источников:
    # N», F6/F6-бис — без сверки здесь тот же дефект прошёл бы незамеченным
    # во второй раз).
    if verified is not None:
        unused_ids = sorted({f["id"] for f in verified} - used)
        claimed_unused = meta.get("неиспользованные_факты", [])
        if sorted(claimed_unused) != unused_ids:
            problems.append(
                "frontmatter «неиспользованные_факты» (%s) не совпадает с реальным подсчётом "
                "по проверенным фактам (%s)" % (sorted(claimed_unused), unused_ids))

        real_sources_used = len({defs[fid]["источник"] for fid in used if fid in defs})
        claimed_n = meta.get("источников")
        if claimed_n is not None and str(claimed_n) != str(real_sources_used):
            problems.append(
                "frontmatter «источников: %s» не совпадает с реальным числом различных "
                "источников среди использованных сносок (%d)" % (claimed_n, real_sources_used))
        unused_report = unused_ids
    else:
        unused_report = meta.get("неиспользованные_факты", [])

    return {
        "ок": not problems,
        "проблемы": problems,
        "источники_без_цитаты": unused_report,
    }
