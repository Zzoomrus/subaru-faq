"""Проход 2: сборка готовой статьи из прозы ИИ и проверенных фактов.

Ценность этого модуля не в том, что он красиво форматирует markdown, а в
том, что он не даёт ИИ солгать в единственном месте, где ложь была бы
незаметна: в самой сноске. ИИ видит только `articles/проверено/<ключ>.json`
(выход `facts.check_all`, задача 4) — факты, чья цитата уже механически
сверена с телом заметки-источника, — и ставит в прозе маркер `[^f3]`.
**Содержимое** сноски (цитату, подпись, ссылку) собирает этот модуль из
данных факта, а не парсит из текста ИИ: если бы сноску набирал ИИ, он мог
бы написать верную цитату при неверной ссылке (или верную цитату под чужим
именем), и проверка сошлась бы на цитате. Поэтому черновик, в котором уже
стоит готовое определение сноски (`^[^f1]:` в начале строки), отбраковывается
целиком, а не молча перезаписывается кодом — иначе ИИ мог бы подписать
настоящую, дословно верную цитату чужим именем и датой, а ни этот модуль (он
не сверяет автора/дату с базой — их и негде взять, кроме базы, из которой
`facts.check_all` их уже проставил), ни `verify.py` задачи 6 (в его таблице
проверок автора/даты нет вовсе) такую подмену не поймали бы.

**Два вида сноски, не один.** У реплики форумчанина/блогера есть автор и
дата (`facts._lookup_meta` берёт их из базы). У записи FAQ — нет: у неё нет
автора-человека, а единственная дата в базе — момент, когда страницу СНЯЛ
краулер, а не когда её написали; подставить её как «дату» было бы обманом
того же рода, против которого затеян весь проект (см. `facts._lookup_meta`,
случай FAQ). Поэтому `_footnote_line` не выбирает один из двух жёстко
заданных шаблонов, а собирает подпись из того, что у факта есть: код
одинаково обрабатывает случай, когда ключей `автор`/`дата` у факта нет
вовсе (программные вызовы `facts.check_all` без `conn`), и случай, когда они
есть, но `None` или пустая строка (FAQ-факт, полученный `facts.check_all` с
`conn` под рукой) — оба дают один и тот же безподписной вид.

Ссылки в сносках не резолвятся и не проверяются заново здесь: имя заметки и
якорь уже прошли через `check_mirror` внутри `facts.check_one` на проходе 1
(Global Constraint №3 фазы — своей цепочки резолва не писать), а повторная
проверка дословности цитаты — работа `verify.py` (задача 6), а не этого
модуля. Дублировать её здесь значило бы завести вторую цепочку резолва одного
и того же знания — урок Ф2 (`local_path`), который эта фаза обязана не
повторить.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from . import check_mirror, notes

# Маркер сноски в прозе черновика — то, что ставит ИИ: `[^f1]`, `[^f12]` и
# т.п. Идентификатор — всё до `]`, без пробелов (ровно те `id`, что выдаёт
# `facts.check_all`: `f1`, `f2`, …).
_MARKER = re.compile(r"\[\^([^\]\s]+)\]")

# Строка ОПРЕДЕЛЕНИЯ сноски — «маркер, сразу двоеточие, и перед маркером на
# СТРОКЕ нет ничего, кроме пробельных символов, знаков списка и угловых
# скобок цитаты». Если такая строка уже стоит в черновике, значит её набрал
# ИИ, а не код: это и есть дыра, которую задача обязана закрыть (см.
# докстринг модуля).
#
# Круг 1 (нулевой отступ) и круг 2 (класс ведущих символов `[ \t>]*`, тоже
# по колонке 0) держались привязкой к НАЧАЛУ СТРОКИ — ревьюер перечислил 20
# форм за пять минут и 13 из них проходили (маркеры списков, NBSP, нулевая
# ширина и т.п.: префиксов бесконечно много, перечислить их все нельзя).
# Круг 3 убрал привязку к началу строки вовсе («маркер, сразу двоеточие», в
# любом месте текста) — это закрыло все 20+ форм обхода, но заодно накрыло
# ЧЕСТНУЮ прозу: маркер в конце придаточного, за которым обычное русское
# двоеточие вводит пояснение (живая находка пилота статей, статья «Износ
# двигателей»: «...усечённой боковой поверхностью**[^f17]:** у таких
# поршней низкий расход объясняется...» — сборка отказала на месте, где
# автор просто продолжил мысль после сноски).
#
# Правило круга 4 — СРЕДНЕЕ, а не третья точка на той же оси «шире/уже»:
# запрет на префикс СТРОКИ (не текста целиком) вместо запрета на префикс
# СИМВОЛА (не начала строки вовсе). Список допустимых символов ПЕРЕД
# маркером конечен и перечислим (пробел, знаки списка, `>`) в отличие от
# бесконечного списка того, что вообще может стоять в прозе ПЕРЕД словом,
# — та же логика «закрытый класс», что у служебных слов в `notes.py`.
# Закрывает обе стороны одним условием: все 20+ форм обхода (круг 2) как
# раз и начинают строку такими символами (это и была их атака — притвориться
# началом блока), а честная проза — нет, перед маркером всегда стоит текст
# самого предложения. Второй довод сильнее первого: если у Obsidian для
# распознавания определения сноски нужно начало строки (а оно нужно — это
# блочная, не инлайновая конструкция), то строка, где перед маркером стоит
# обычный текст, вообще не РЕНДЕРИТСЯ как определение — а то, что не
# рендерится сноской, не может быть и подделкой сноски.
#
# Символы формата Unicode (категория `Cf` — нулевая ширина, BOM, мягкий
# перенос и т.п.) снимаются ПЕРЕД проверкой той же функцией, что уже снимает
# их при разборе чисел (`notes._strip_format_chars`) — общее знание «эти
# символы невидимы и не несут смысла», не новый список для второго
# потребителя. Проверено на живых данных, на корпусе из 22 форм обхода
# круга 2 (`.superpowers/sdd/.../task-5-rereview/атака-f1.py`) и на честной
# прозе (маркер в заголовке, рядом с вики-ссылкой, время `12:30`, двоеточие
# после обычного слова, двоеточие-пояснение после маркера в конце фразы).
_LINE_PREFIX = r"[\s>*+\-.\d)]*"
_EMBEDDED_DEFINITION = re.compile(r"^%s\[\^[^\]]+\]:" % _LINE_PREFIX, re.M)

# Экранированные скобки (`\[^f1\]:`, форма корпуса круга 2) снимаются ДО
# проверки, а не добавлением `\` в `_LINE_PREFIX`: экран перед `[`/`]` —
# то же «невидимо для читателя» знание, что у Cf-символов выше (Obsidian
# рендерит `\[` как голую `[`, отличить их не может НИКТО, кто смотрит на
# страницу, а не на исходник), а не отдельный допустимый префикс. Различие
# важно: круг-2 корпус экранирует ОБЕ скобки (`\[^f1\]:`), и эта форма
# ловится и без снятия экрана — `_MARKER` захватывает хвостовой `\` в id,
# `render()` отбивает её как ссылку на несуществующий факт «f1\». Но форма
# с экраном только на ОТКРЫВАЮЩЕЙ скобке (`\[^f1]:`, `id` — чистое «f1»,
# совпадает с настоящим фактом) без этого снятия проходит НЕЗАМЕЧЕННОЙ —
# то же семейство атаки, что и у корпуса, просто не входящее в его 22
# формы буквально. Снимает ТОЛЬКО пары `\[`/`\]` (случайный одиночный `\`
# в проза не трогается), поэтому не открывает дыру для честного текста.
_ESCAPED_BRACKET = re.compile(r"\\([\[\]])")

# F4 ревью: маркер спрятанный в код-блоке/инлайн-коде/HTML-комментарии
# считался «использованным», хотя в отрендеренной статье такой ссылки
# читатель не увидит вовсе (HTML-комментарий не рендерится, код-блок и
# инлайн-код рендерят маркер буквально, не как сноску-ссылку) — и замер
# спеки §6 «доля источников, не процитированных ни разу» обнулялся: проза
# без опоры проходила молча. Вырезаются ПЕРЕД поиском маркеров, а не после
# — иначе маркер внутри такого блока всё равно попадёт в `used_ids`.
_FENCED_CODE = re.compile(r"```.*?```", re.S)
_HTML_COMMENT = re.compile(r"<!--.*?-->", re.S)
_INLINE_CODE = re.compile(r"`[^`\n]*`")
# F3-бис ре-ревью: `%%…%%` — родной комментарий Obsidian, в режиме чтения
# невидим полностью (в отличие от HTML-комментария, который часть визоров
# показывает как HTML). Маркер, спрятанный внутри такого комментария, читатель
# не увидит никогда, значит и «использованным» его считать нельзя — тот же
# довод, что для fenced-код-блока, инлайн-кода и HTML-комментария выше.
_OBSIDIAN_COMMENT = re.compile(r"%%.*?%%", re.S)


def _strip_non_prose(text: str) -> str:
    text = _FENCED_CODE.sub(" ", text)
    text = _HTML_COMMENT.sub(" ", text)
    text = _OBSIDIAN_COMMENT.sub(" ", text)
    return _INLINE_CODE.sub(" ", text)


class DraftError(Exception):
    """Черновик прохода 2 непригоден для сборки: маркер без проверенного
    факта, встроенное ИИ определение сноски, отсутствующие метаданные."""


def used_ids(draft: str) -> list[str]:
    """Идентификаторы фактов, на которые проза ссылается маркерами, в
    порядке первого появления, без повторов — ровно то множество, для
    которого нужно отрендерить ОДНО определение сноски каждому (тест
    `test_every_footnote_definition_appears_once`: маркер, повторённый в
    прозе несколько раз, — не повод дублировать сноску).

    Маркеры внутри fenced-код-блоков, инлайн-кода, HTML-комментариев и
    комментариев Obsidian `%%…%%` не считаются использованием
    (`_strip_non_prose`, F4/F3-бис ревью) — читатель не увидит там живой
    ссылки на источник, а значит утверждение ею и не подкреплено.
    """
    seen: list[str] = []
    for m in _MARKER.finditer(_strip_non_prose(draft)):
        fid = m.group(1)
        if fid not in seen:
            seen.append(fid)
    return seen


def _footnote_line(fact: dict) -> str:
    """Собирает ОДНУ строку определения сноски из данных факта — не из
    текста ИИ (см. докстринг модуля).

    Подпись — то, что у факта есть: автор и дата, если они есть и непустые
    (форум/блог), иначе ничего вовсе (FAQ). `fact.get(...) or ""` нарочно
    уравнивает три формы отсутствия — ключа нет, ключ `None`, ключ `""` —
    все три реально встречаются на выходе `facts.check_all` (без базы ключи
    отсутствуют; с базой FAQ получает явный `None`) и не должны давать
    разные сноски.

    Цитата канонизируется `notes.normalize_spaces` (F2 ревью): дословность
    сверяется по этой же функции (Global Constraint №1 — перенос строки в
    заметке не подделка), значит цитата, законно прошедшая проход 1, МОЖЕТ
    содержать `\n`. Без канонизации здесь сырой перенос вываливал бы вторую
    строку цитаты, а с ней — подпись и ссылку, за пределы markdown-строки
    определения сноски: привязка утверждения к источнику разрушалась бы на
    обычных многострочных постах форума, без всякого злоумышленника.
    """
    quote = notes.normalize_spaces(fact.get("цитата", ""))
    parts = []
    author = (fact.get("автор") or "").strip()
    if author:
        parts.append(author)
    when = (fact.get("дата") or "").strip()
    if when:
        parts.append(when)
    parts.append("[[%s]]" % fact["источник"])
    return "[^%s]: «%s» — %s" % (fact["id"], quote, ", ".join(parts))


def render(draft: str, verified: list[dict], meta: dict) -> str:
    """Собирает готовый markdown статьи: frontmatter + прозу черновика +
    раздел сносок, отрендеренный из `verified` (см. докстринг модуля —
    сноску набирает код, не ИИ).

    Отказывает (`DraftError`), если:
    - в черновике уже стоит готовое определение сноски (её обязан
      набрать код, а не ИИ — иначе проверка дословности сошлась бы на
      настоящей цитате при подменённой подписи);
    - маркер ссылается на факт, которого нет среди `verified` (ИИ
      сослался на то, чего проход 1 не подтвердил, или опечатался в id).

    Неиспользованный факт (проверенный, но не упомянутый в прозе) не
    выбрасывается молча — он попадает и в поле frontmatter
    `неиспользованные_факты`, и в видимый коллаут в теле статьи: спека §6
    требует измерять долю фактов, которые ИИ проигнорировал, и молчаливое
    выбрасывание превратило бы этот замер в ноль.
    """
    detection_view = notes._strip_format_chars(_ESCAPED_BRACKET.sub(r"\1", draft))
    embedded = _EMBEDDED_DEFINITION.search(detection_view)
    if embedded:
        raise DraftError(
            "черновик содержит готовое определение сноски «%s» — его обязан "
            "рендерить код (pipeline.articles.render), а не ИИ: иначе подмену "
            "подписи при верной цитате никто не поймает" % embedded.group(0))

    by_id = {fact["id"]: fact for fact in verified}
    ids = used_ids(draft)
    missing = [fid for fid in ids if fid not in by_id]
    if missing:
        raise DraftError(
            "проза ссылается на факт(ы), которых нет среди проверенных: %s"
            % ", ".join(missing))

    unused = [fact["id"] for fact in verified if fact["id"] not in ids]

    frontmatter = ["---", "type: статья"]
    if meta.get("узел"):
        frontmatter.append("узел: %s" % meta["узел"])
    if meta.get("модель"):
        frontmatter.append("модель: [%s]" % ", ".join(meta["модель"]))
    # F6 ревью: считает РАЗЛИЧНЫЕ источники, а не факты — несколько фактов
    # из одного поста/ответа не делают статью подкреплённой большим числом
    # источников, а старое `len(verified)` завышало охват в разы (5 при трёх
    # постах одной темы в живой статье, 4 при одном источнике FAQ).
    #
    # R4 ре-ревью (F6-бис): считает источники ИСПОЛЬЗОВАННЫХ фактов (`ids`),
    # а не всех проверенных (`verified`) — факт, на который проза не
    # сослалась ни разу (он же в `unused` ниже), не должен раздувать
    # заявленный охват статьи: это тот же класс завышения, что чинила F6,
    # только на уровне отдельного факта, а не дубликата источника.
    frontmatter.append("источников: %d" % len({by_id[fid]["источник"] for fid in ids}))
    if unused:
        frontmatter.append("неиспользованные_факты: [%s]" % ", ".join(unused))
    # F5/R3 ревью: НИКАКОГО обращения к сегодняшней дате здесь — ни как
    # значения по умолчанию, ни за резервным путём, и `build` (ниже) после
    # R3 фолбэка на mtime черновика тоже не делает. `собрано` рендерится
    # ТОЛЬКО если он явно есть в `meta`, иначе строка вовсе не добавляется.
    # Обращение к «сейчас» ломает Global Constraint №8 (побитовая
    # пересборка) ровно один раз в сутки — на смене дня, а mtime — при
    # каждом свежем `git clone`/`checkout`, поэтому обычная проверка «собрал,
    # пересобрал, diff пуст» ни тот, ни другой дефект не видит: единственный
    # источник даты — явное поле черновика, решает автор черновика, а не код.
    if meta.get("собрано"):
        frontmatter.append("собрано: %s" % meta["собрано"])
    frontmatter.append("---")

    # `strip("\n")`, не только `rstrip`: `_parse_draft` возвращает тело
    # черновика с ведущим переносом строки (пустая строка сразу после
    # закрывающей `---` frontmatter) — без обрезки с обоих концов между
    # заголовком статьи и прозой оставалась бы лишняя пустая строка.
    body_parts = [draft.strip("\n")]
    if unused:
        body_parts.append("")
        body_parts.append("> [!warning] Факты не использованы: %s" % ", ".join(unused))

    out = ["\n".join(frontmatter), "", "# %s" % meta.get("заголовок", ""), "",
           "\n".join(body_parts)]
    if ids:
        out += ["", "## Сноски", "", "\n".join(_footnote_line(by_id[fid]) for fid in ids)]
    return "\n".join(out) + "\n"


# --- build: черновик + проверенные факты -> заметка в wiki/Статьи ---------

# frontmatter черновика — простые пары `ключ: значение`, значение — либо
# скаляр, либо список `[a, b]` (ровно тот минимум, который нужен статье;
# полноценный YAML-парсер этому проекту нигде не требовался, см. docstring
# `check_mirror._strip_frontmatter` — везде до этой задачи frontmatter только
# ОТРЕЗАЛИ, а не читали обратно как структуру).
def _parse_draft(path: Path) -> tuple[dict, str]:
    text = Path(path).read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise DraftError("в черновике «%s» нет frontmatter с метаданными статьи (заголовок/путь)" % path)
    end = text.find("\n---\n", 4)
    if end == -1:
        raise DraftError("frontmatter черновика «%s» не закрыт строкой `---`" % path)
    meta: dict = {}
    for line in text[4:end].splitlines():
        line = line.strip()
        if not line or ":" not in line:
            continue
        key, _, value = line.partition(":")
        key, value = key.strip(), value.strip()
        if value.startswith("[") and value.endswith("]"):
            meta[key] = [x.strip() for x in value[1:-1].split(",") if x.strip()]
        else:
            meta[key] = value.strip('"')
    return meta, text[end + 5:]


# F3 ревью: `путь`/`заголовок` идут из черновика ИИ прохода 2 в путь файла
# на диске без проверки — обход каталога (`путь: ../../../tmp/x`) и
# абсолютный путь (`путь: /tmp/x` — `Path("a") / "/tmp/x"` в pathlib МОЛЧА
# отбрасывает левую часть и получившийся путь становится абсолютным)
# писали файл вне `wiki/Статьи` без единой жалобы; слэш в заголовке
# («Ремонт EJ20/EJ25» — обычное дело для статьи про Subaru) падал
# `FileNotFoundError`, а не внятным `DraftError`.
_UNSAFE_PATH_CHARS = re.compile(r"[\\/]")


def _require_safe_path_component(value: str, label: str, draft_path: Path) -> None:
    """`value` становится ОДНИМ компонентом пути (имя папки или файла), а
    не подстрокой пути — разделители запрещены целиком, не только `..`."""
    if _UNSAFE_PATH_CHARS.search(value) or value in (".", ".."):
        raise DraftError(
            "в черновике «%s» значение поля «%s» (%r) не годится в качестве "
            "имени файла/папки — разделители путей (`/`, `\\`) и значения "
            "`.`/`..` запрещены" % (draft_path, label, value))


def _require_safe_section_path(value: str, draft_path: Path) -> None:
    """`путь` — папка статьи ВНУТРИ `wiki/Статьи`, и по спеке (§7) она бывает
    вложенной: модельная ось — `Модели/Leone`, `Модели/GC8`. Поэтому слэш
    здесь разрешён как разделитель компонентов, но КАЖДЫЙ компонент
    проверяется тем же правилом, что и одиночное имя: пустой компонент
    (ведущий `/` = абсолютный путь, `a//b`), `.`/`..` (обход каталога) и
    обратный слэш — `DraftError`. Второй рубеж (`resolve()` внутри
    `wiki/Статьи` в `build`) остаётся как был."""
    parts = value.split("/")
    if "\\" in value or any(not part or part in (".", "..") for part in parts):
        raise DraftError(
            "в черновике «%s» значение поля «путь» (%r) не годится в качестве "
            "папки статьи — допустимы только вложенные имена через `/` "
            "(например `Модели/Leone`); пустые компоненты, `.`/`..` и `\\` "
            "запрещены" % (draft_path, value))


def _draft_target(meta: dict, draft_path: Path, articles_dir: Path) -> Path:
    """Извлекает и проверяет `заголовок`/`путь` черновика, возвращает
    НЕразрешённый путь `<articles_dir>/<путь>/<заголовок>.md`.

    Общий расчёт для `build()` (куда пишет ЭТА сборка) и для
    `prune_orphans` (куда пишет КАЖДЫЙ черновик, включая не тот, что
    сейчас собирается) — один код на два потребителя, а не две копии,
    которые могут разойтись молча (тот же урок Ф2, что у
    `check_mirror.title_collisions`)."""
    title = meta.get("заголовок")
    if not title:
        raise DraftError("в черновике «%s» не задан заголовок статьи (frontmatter `заголовок:`)"
                          % draft_path)
    section_path = meta.get("путь")
    if not section_path:
        raise DraftError("в черновике «%s» не задан `путь` (папка узла в wiki/Статьи) — код "
                          "не угадывает её из «узел», это должно быть решено явно" % draft_path)
    _require_safe_path_component(title, "заголовок", draft_path)
    _require_safe_section_path(section_path, draft_path)
    return articles_dir.joinpath(*section_path.split("/")) / ("%s.md" % title)


# Признак «это файл написал render()», проверяемый по ФОРМЕ СОДЕРЖИМОГО, не
# имени: у вложений (`mirror.prune_assets`) есть форма имени файла генератора
# (`attachments.ASSET_NAME_RE`, `<16 hex><ext>`) — у статьи заголовок и имя
# файла выбирает человек словами, точно так же, как автор личной заметки,
# вручную положенной в тот же каталог; формы имени, отличающей одно от
# другого, не существует. `render()` (см. выше) безусловно пишет ПЕРВОЙ
# строкой frontmatter (сразу после `---`) `type: статья` и ничего другого в
# `wiki/Статьи` этот код не пишет — эта строка и есть тот же по роли, но не
# по механике признак: не результат догадки по имени, а фиксированный след,
# который оставляет сам генератор.
_FRONTMATTER_TYPE_ARTICLE = re.compile(r"^type:\s*статья\s*$", re.M)


def _is_generated_article(path: Path) -> bool:
    """True, если `path` несёт frontmatter-след `render()` (см. выше).
    Файл без этого следа не трогается никогда — что бы ни показало
    сравнение с текущим набором черновиков."""
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False
    if not text.startswith("---\n"):
        return False
    end = text.find("\n---\n", 4)
    if end == -1:
        return False
    return bool(_FRONTMATTER_TYPE_ARTICLE.search(text[4:end]))


def prune_orphans(root: Path) -> int:
    """Убирает из `<root>/wiki/Статьи` файлы статей, которым больше не
    соответствует ни один черновик — переименование заголовка/пути в
    черновике оставляет старый файл под старым именем, а никакая проверка
    целостности (`check_mirror.check`) это не ловит: ссылки и якоря у
    сироты в порядке, она просто больше никому не нужна. Тот же приём, что
    `mirror.prune_assets` использует для осиротевших вложений — вызывается
    из `build()` при каждой успешной сборке (для статей нет отдельного
    прохода «собрать все», как `mirror.write_all` у вложений, поэтому
    пересчёт целевого множества заново на каждый вызов — не оптимизация,
    а единственный способ поддерживать дерево согласованным без отдельного
    состояния на диске).

    Предохранитель — как у `prune_assets`, но по своему условию: у вложений
    он «ни одной заметки не записано», у статей — «ни одного черновика не
    разобралось» (пустой/не существующий `articles/черновики`, либо все
    файлы в нём непригодны для сборки). В обоих случаях каталог статей не
    трогается вовсе — неверный `--root` не должен стирать существующие
    статьи как «сирот», а черновик, который сейчас не собрать, не даёт
    оснований удалить ЧУЖОЙ файл: он просто выпадает из проверки для
    своего собственного ключа, как и при обычном `build()` этого ключа.
    """
    root = Path(root)
    articles_dir = root / "wiki" / "Статьи"
    drafts_dir = root / "articles" / "черновики"
    if not articles_dir.exists() or not drafts_dir.exists():
        return 0

    articles_root_resolved = articles_dir.resolve()
    keep: set[Path] = set()
    for draft_path in sorted(drafts_dir.glob("*.md")):
        try:
            meta, _ = _parse_draft(draft_path)
            out_path = _draft_target(meta, draft_path, articles_dir)
        except DraftError:
            continue
        resolved = out_path.resolve()
        if resolved == articles_root_resolved or articles_root_resolved in resolved.parents:
            keep.add(resolved)

    if not keep:
        return 0

    removed = 0
    for path in sorted(articles_dir.rglob("*.md")):
        if path.resolve() in keep:
            continue
        if not _is_generated_article(path):
            continue
        path.unlink()
        removed += 1
    return removed


def build(key: str, root: Path) -> Path:
    """Собирает статью с ключом `key` и пишет её в
    `<root>/wiki/Статьи/<путь>/<заголовок>.md`.

    Потребляет два файла с фиксированными путями (тот же приём, что у
    `pipeline.run` для `articles/факты`/`articles/проверено` — фиксированное
    место по ключу, не аргумент): `<root>/articles/черновики/<key>.md`
    (проза ИИ с маркерами + frontmatter — заголовок, путь, узел, модель) и
    `<root>/articles/проверено/<key>.json` (выход `facts.check_all`, задача
    4 — читается поле `проверено`).

    `путь` — папка `wiki/Статьи/<путь>/`, задаётся ЯВНО во frontmatter
    черновика, а не выводится кодом из `узел`: правило вида «взять `узел` и
    сделать первую букву заглавной» ломается на акронимах («грм» ->
    `Grm`/`Грм`, а не `ГРМ`), и молчаливое неверное угадывание пути — ровно
    тот класс ошибки, против которого затеяна вся фаза. Отсутствие `путь`
    или `заголовок` — `DraftError`, а не подстановка по умолчанию.

    `собрано` — та же схема, что `путь`, и ОБЯЗАТЕЛЬНАЯ ровно в том же
    смысле (R3 ре-ревью, уточнение бригадира после первой версии фикса):
    рендерится исключительно из явного поля frontmatter черновика, без
    какого-либо фолбэка — ни `date.today()` (F5, обнаруживало себя раз в
    сутки на смене дня), ни mtime файла черновика (первая починка F5: в
    пределах ОДНОГО рабочего дерева давала байт-в-байт одинаковый результат,
    но mtime переписывается при `git clone`/`checkout`/`stash`/`clean` —
    значит в СВЕЖЕМ клоне все статьи получили бы дату клона и разошлись бы с
    уже закоммиченными, а побитовая пересборка в чистый каталог и есть
    условие сдачи любой задачи, меняющей генераторы, Global Constraint №8).
    Отсутствие поля — `DraftError`, а не молчаливый пропуск строки: спека
    перечисляет `собрано` в составе полей статьи по контракту, а не как
    опцию, и молчаливая потеря даты сборки на пилоте в 73 темах была бы
    ровно тем классом тихой потери информации, против которого затеяна вся
    фаза. (`render`, вызываемый напрямую, а не через `build`, по-прежнему
    просто опускает строку при отсутствии `собрано` в `meta` — требование
    обязательности живёт здесь, а не в `render`, симметрично тому, как
    `путь` тоже не проверяется в `render`.)
    """
    root = Path(root)
    draft_path = root / "articles" / "черновики" / ("%s.md" % key)
    verified_path = root / "articles" / "проверено" / ("%s.json" % key)
    if not draft_path.exists():
        raise FileNotFoundError("черновик не найден: %s" % draft_path)
    if not verified_path.exists():
        raise FileNotFoundError("проверенные факты не найдены: %s" % verified_path)

    meta, draft = _parse_draft(draft_path)
    title = meta.get("заголовок")
    if not title:
        raise DraftError("в черновике «%s» не задан заголовок статьи (frontmatter `заголовок:`)"
                          % draft_path)
    if not meta.get("путь"):
        raise DraftError("в черновике «%s» не задан `путь` (папка узла в wiki/Статьи) — код "
                          "не угадывает её из «узел», это должно быть решено явно" % draft_path)
    if not meta.get("собрано"):
        raise DraftError(
            "в черновике «%s» не задано `собрано` (дата сборки статьи) — код "
            "не подставляет её ни из mtime файла, ни из текущей даты: mtime "
            "переписывается при git clone/checkout и ломает побитовую "
            "пересборку в чистый каталог (Global Constraint №8), а "
            "«сегодня» ломает воспроизводимость на смене суток; решается "
            "явно, тем же способом, что и «путь»" % draft_path)

    # R6 ре-ревью: `out_path` строится от ПЕРЕДАННОГО `root`, не резолвленного
    # — контракт функции документирован как «пишет <root>/wiki/Статьи/<путь>/
    # <заголовок>.md», то есть путь ОТ `root`, а не абсолютный канонический.
    # `.resolve()` нужен только для проверки рубежа ниже (символьные ссылки,
    # `..`, юникод-трюки) и не должен просачиваться в возвращаемое значение —
    # иначе, например, macOS-симлинк `/var` -> `/private/var` в `root`
    # разворачивается в путь, для которого `relative_to(root)`/`root / ...`
    # у вызывающего кода перестают совпадать (сломанная оснастка ре-ревью).
    #
    # Вычислен ДО загрузки фактов/рендера (не только до записи файла) —
    # рубежи ниже (безопасность пути, коллизия имени) не должны тратить
    # время на факты и прозу, если статья всё равно не будет записана.
    # `_draft_target` заодно проверяет безопасность обоих компонентов
    # (`_require_safe_path_component`) — общий с `prune_orphans` расчёт.
    articles_dir = root / "wiki" / "Статьи"
    out_path = _draft_target(meta, draft_path, articles_dir)
    # Второй, независимый от `_require_safe_path_component` рубеж (F3):
    # итоговый путь обязан фактически лежать внутри `wiki/Статьи` после
    # `resolve()` — символьные ссылки, юникод-трюки и всё, что первая
    # проверка не предвидела, ловятся здесь. Резолвим ОБЕ стороны сравнения
    # (и `articles_dir`, и `out_path`) — иначе, например, симлинк в самом
    # `root` дал бы ложное несовпадение корней при полностью безопасном пути.
    articles_root_resolved = articles_dir.resolve()
    resolved = out_path.resolve()
    if resolved != articles_root_resolved and articles_root_resolved not in resolved.parents:
        raise DraftError(
            "итоговый путь статьи «%s» выходит за пределы «%s» — проверь поля "
            "«путь»/«заголовок» черновика «%s»" % (resolved, articles_root_resolved, draft_path))

    # Коллизия заголовка с именем/псевдонимом заметки зеркала — ПЕРВЫЙ
    # рубеж, до записи файла (не только последний, в `verify.py`, после
    # того как статья уже полностью написана): короткое номинативное
    # название узла — самый частый способ назвать тему форума, и статья
    # про тот же узел называется так же по той же причине — совпадение не
    # редкость, а закономерность (30% алиасов тем форума короче трёх слов
    # и уже в форме заголовка статьи; 80 из них делят имя с ДРУГОЙ
    # заметкой зеркала ещё до единой статьи). `title_collisions` — общая
    # функция с проверкой `verify.py` (Global Constraint фазы №3 — два
    # потребителя одного знания не заводят две копии, которые разойдутся
    # молча, как разошлись `sync_to_db`/`local_path` в Ф2).
    # `resolved` уже проверен ВЫШЕ как лежащий внутри `articles_dir`
    # (`wiki_root / "Статьи"`), значит и внутри `wiki_root` — `relative_to`
    # здесь не может бросить исключение неожиданно.
    wiki_root = root / "wiki"
    own_key = resolved.relative_to(wiki_root.resolve()).with_suffix("").as_posix()
    mirror_notes, by_name = check_mirror.build_notes_index(wiki_root)
    alias_index = check_mirror.build_alias_index(mirror_notes)
    collisions = check_mirror.title_collisions(title, by_name, alias_index, own_key=own_key)
    if collisions:
        raise DraftError(
            "заголовок статьи «%s» (черновик «%s») совпадает с именем/псевдонимом заметки «%s» "
            "в зеркале — ссылка на этот адрес станет неоднозначной и может молча резолвиться не "
            "туда. Уточни заголовок ПО СУЩЕСТВУ — чем статья отличается от источника (диагностика, "
            "симптомы, способ ремонта — например, «Диагностика датчика детонации» вместо голого "
            "«Датчик детонации»), а не приписывай общий суффикс вроде марки автомобиля: он ничего "
            "не различает по смыслу и не гарантирует уникальность сам"
            % (title, draft_path, ", ".join(collisions)))

    verified = json.loads(verified_path.read_text(encoding="utf-8"))["проверено"]
    text = render(draft, verified, meta)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(text, encoding="utf-8")

    # Сирота от переименования (задача 5-бис): если этот же ключ раньше
    # собирался под другим заголовком/путём, старый файл остаётся на диске
    # — ни одна проверка целостности (`check_mirror.check`) этого не видит
    # (ссылки и якоря сироты в порядке, у неё просто нет читателя). Нет
    # отдельного прохода «собрать все статьи», как `mirror.write_all` у
    # вложений, поэтому уборка идёт ПОСЛЕ каждой успешной записи, не только
    # после последней — см. `prune_orphans`.
    prune_orphans(root)
    return out_path
