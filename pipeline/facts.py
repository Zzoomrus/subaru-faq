"""Проход 1: приём и механическая проверка фактов, выданных ИИ.

Ценность фазы не в том, что ИИ пишет связный текст, а в том, что соврать
ему нечем: факт, чья цитата не найдена дословно в теле заметки, до прозы не
доживает. Поэтому проверка здесь — не валидация формата, а гейт.

Сверяется ТЕЛО ЗАМЕТКИ (канон дословной проверки, `docs/контракт-зеркала.md`
§2), причём очищенное от текста генератора (`notes.citable`): в зеркале
6341 пометка «(изображение не сохранилось: …)», и цитата из неё прошла бы
проверку, подтвердив несуществующие слова автора.

Имя заметки резолвится через `check_mirror.build_notes_index`/`resolve_note`
— ту же цепочку, которой Obsidian и `check_mirror.check` разрешают
`[[Тема 1#Пост 100]]`. Global Constraint фазы №3 запрещает писать здесь свою:
два потребителя одного знания, разошедшиеся молча, — урок Ф2 (`local_path`).
"""
from __future__ import annotations

import re
import sqlite3
from functools import lru_cache
from pathlib import Path

from . import check_mirror, notes

# Разбор `источника` факта на имя заметки и номер поста/комментария из
# якоря — нужно и для резолва цитируемой секции, и чтобы достать автора/
# дату из базы (`_lookup_meta` ниже). Три формы имени заметки исчерпывают
# закрытый список из `docs/контракт-зеркала.md` §1.
_NOTE_THEME = re.compile(r"^Тема (\d+)$")
_NOTE_FAQ = re.compile(r"^FAQ (старый )?(\d+)$")
_NOTE_BLOG = re.compile(r"^Блог (\S+) (\d+)$")
_ANCHOR_POST = re.compile(r"^Пост (\d+)$")
_ANCHOR_COMMENT = re.compile(r"^Комментарий (\d+)$")
_ANCHOR_QUESTION = re.compile(r"^Вопрос$")
_ANCHOR_ANSWER = re.compile(r"^Ответ$")
_ANCHOR_RECORD = re.compile(r"^Запись$")

#: Закрытый список ВИДОВ ЯКОРЯ, цитируемых секцией (`docs/контракт-зеркала.md`
#: §1: `#Пост <MID>`, `#Вопрос`, `#Ответ`, `#Запись`, `#Комментарий <N>` —
#: другого не существует). Н2 ревью задачи 4: `check_one` раньше принимал
#: якорем ЛЮБОЙ заголовок заметки — заголовки-контейнеры генератора
#: («Комментарии», «Запись» с большой буквы у контейнера — нет, но, например,
#: H1 темы) не пробивались только потому, что их текст случайно не совпадал
#: ни с одной секцией; страховки не было, только форма заметок. Проверка
#: формы здесь не привязана к типу заметки (можно сослаться на `FAQ N#Пост
#: 1` формой валидно, но `notes.section` такой заголовок в FAQ-заметке не
#: найдёт и вернёт `None` — тот же результат, что и было, просто по другой
#: причине), это специально: тип-специфичная сверка ничего не покупает сверх
#: уже существующей проверки «якорь есть в заметке».
_ANCHOR_FORMS = (_ANCHOR_POST, _ANCHOR_COMMENT, _ANCHOR_QUESTION, _ANCHOR_ANSWER, _ANCHOR_RECORD)

#: Минимальная длина цитаты — В ЗНАКАХ, ПОСЛЕ схлопывания пробелов (Н6
#: ревью задачи 4). Гейт проверяет только существование дословной
#: подстроки; связь цитаты с полем «суть» машине недоступна ничем, кроме
#: длины, а длину проверить можно. Без порога `{"цитата": "мм", "суть":
#: "любое утверждение, которого в источнике нет"}` — честный проверенный
#: факт с настоящей атрибуцией (живой пример ревью).
#:
#: ВАЖНО: НЕ переделывать на подсчёт СЛОВ — этот вариант уже был и отменён
#: (см. историю коммитов и `task-4-review-findings.md`: ревьюер сперва
#: рекомендовал именно слова). Причина отмены — счётчик слов отверг бы
#: ДЛИННУЮ однословную техническую цитату: VIN `JF1GDDLF37G076103` (17
#: знаков, 1 слово) или артикул `22611AD982` (10 знаков, 1 слово) —
#: самодостаточные факты, порог «не меньше 3 слов» убил бы их полностью.
#: Первая живая статья фазы цитирует именно такой VIN. Живой контрпример,
#: которым и была поймана ошибка: реальный, уже атрибутированный факт
#: статьи «12 - Коробка передач» (2 буквенных слова) отваливался при
#: пороге в 3 слова, хотя цифра здесь несёт смысл наравне со словом.
#: Измерение, на которое опиралась рекомендация «считать слова» («порог в
#: 3 слова стоит нуля настоящих фактов»), само было сделано на выборке,
#: отобранной условием «предложение с цифрой И не менее трёх слов» — то
#: есть нулевая цена получена ПО ПОСТРОЕНИЮ выборки (круговая фильтрация)
#: и не доказывала вообще ничего про реальное распределение; повторный
#: замер без этого условия подтвердил именно порог в знаках.
#:
#: ЧТО ПОРОГ В 8 ЗНАКОВ ДЕЙСТВИТЕЛЬНО ДАЁТ (не переоценивать): честный
#: пересчёт на живом корпусе — короче 8 знаков 16,6 % предложений, но вся
#: голова этого распределения — мусор разбиения на предложения («у.»,
#: «us.», «com)», «php?»), самодостаточных фактов среди частотных нет;
#: порог отсекает ровно вырожденный случай ревью («мм» — 2 знака, «025 /
#: 2» — 7 знаков) и лежит ниже наблюдавшегося минимума настоящих коротких
#: фактов (12 знаков). НО порог НЕ спасает короткие технические
#: обозначения короче 8 знаков — код двигателя `EJ20` (4 знака), марку
#: масла `5W-30` (5 знаков) он отвергает ТОЖЕ, и это ПРАВИЛЬНО: такие
#: обозначения встречаются в корпусе сотнями раз (замер — 245 разных
#: обозначений, 1070 вхождений короче порога) и сами по себе, без
#: контекста предложения, ничего не подтверждают — от таких цитат порог и
#: должен защищать. Граница проведена по длине, а не по классу
#: «технический идентификатор»: она пропускает длинные идентификаторы
#: (VIN, артикул) и режет короткие (код двигателя, марка масла) — оба
#: класса технические, разница только в числе знаков.
MIN_QUOTE_CHARS = 8

#: Потолок числа РАЗЛИЧНЫХ значений «число+единица» в одной цитате (Н11
#: ре-ревью задачи 6). Нормализация пробелов (`normalize`, обязательна по
#: Global Constraint №1 — перенос строки в источнике не подделка) схлопывает
#: и настоящий абзацный перенос, и границу МЕЖДУ РАЗНЫМИ утверждениями
#: источника в ОДИН пробел — из четырёх абзацев источника («седан 266мм»,
#: «вагон 270мм», «седан 265мм», «вагон 279мм», каждый про свой кузов и
#: свою точку замера) склеенная цитата становится ОДНОЙ строкой с четырьмя
#: значениями сразу. Проверка 5 `pipeline.verify` берёт покрытие числа из
#: ЦИТАТЫ целиком — значит такая широкая цитата подтверждает ЛЮБУЮ
#: перестановку своих же чисел: «спереди у седана 279мм» (реально 266мм)
#: проходила бы, потому что 279 просто ЕСТЬ где-то в цитате. Живой пример
#: ревью — Тема 19033#Пост 160401.
#:
#: Порог — на числе РАЗЛИЧНЫХ значений (`find_number_units`), а не на
#: длине строки: длина сама по себе ничего не говорит об опасности (цитата
#: в 300 знаков с ОДНИМ числом безопасна, цитата в 80 знаков с четырьмя
#: плотно упакованными значениями — нет), а число значений — ровно то, что
#: включает подмену перестановкой. Значение 2 — не произвольное: честный
#: факт либо называет ОДНО значение, либо ОДИН диапазон (что даёт ровно два
#: конца диапазона, `find_number_units` уже считает диапазон двумя
#: значениями) — оба случая пропускает порог "не больше 2"; сама угроза
#: (Н11) начинается с ТРЁХ и больше кандидатов на подстановку. Предел
#: задокументирован в `docs/контракт-зеркала.md` §2 — не молчать о нём, как
#: просило ревью.
MAX_QUOTE_NUMBER_UNITS = 2


def normalize(text: str) -> str:
    """Схлопнуть пробелы: перенос строки в заметке не является подделкой.

    Делегирует `notes.normalize_spaces`, а не заводит свою копию регэкспа —
    у схлопывания пробелов уже есть один потребитель (`pipeline.faq_dedup`,
    задача 1 Ф3) и урок ревью той задачи: два экземпляра одного правила
    разошлись молча (два движка форума бьют абзацы по-разному), и дедуп
    пропустил настоящие дубли, пока сравнение шло сырой строкой. Здесь та
    же природа расхождения — см. докстринг `notes.normalize_spaces`.
    """
    return notes.normalize_spaces(text)


@lru_cache(maxsize=None)
def _notes_index(mirror_root: str) -> tuple[dict[str, str], dict[str, list[str]]]:
    # Кэш по строке корня: в пределах одного прогона `facts check-all` над
    # одной и той же вики дерево не меняется, а фактов — десятки на статью.
    # Без кэша каждый факт заново читал бы текст ВСЕХ заметок корпуса.
    return check_mirror.build_notes_index(Path(mirror_root))


def _resolve_note(mirror_root: Path, name: str) -> tuple[Path | None, str]:
    """Резолвит ИМЯ заметки (без якоря) в файл через `check_mirror` — не
    свою цепочку (Global Constraint №3).

    Возвращает `(путь, причина)`: путь `None`, если заметка не найдена ИЛИ
    имя неоднозначно (несколько заметок с одинаковым именем в разных
    папках — угадывать здесь нельзя, `check_mirror.check` в этом случае
    сверяет объединение их якорей, но для цитаты подстановка чужой заметки
    недопустима), причина — только когда путь `None`.
    """
    notes_index, by_name = _notes_index(str(Path(mirror_root)))
    hits = check_mirror.resolve_note(name, notes_index, by_name)
    if not hits:
        return None, "заметка «%s» не найдена" % name
    if len(hits) > 1:
        return None, "имя «%s» неоднозначно: %s" % (name, ", ".join(sorted(hits)))
    return Path(mirror_root) / (hits[0] + ".md"), ""


def check_one(fact: dict, mirror_root: Path, conn: sqlite3.Connection | None = None) -> tuple[bool, str]:
    """`conn`, если дан, включает проверку ЦИТИРУЕМОСТИ ИСТОЧНИКА
    (`notes.citable_source`, задача 6 Ф3) — дубль FAQ и выдержка блога
    отбраковываются здесь же, до резолва и чтения секции: текст в них
    настоящий (не пометка генератора), значит `citable()` их не ловит, и
    единственный способ узнать про запрет — спросить базу. Без `conn`
    (программные вызовы/тесты без базы под рукой, как и у автора/даты ниже)
    эта проверка пропускается — не становится ложным «источник цитируем».
    """
    source = (fact.get("источник") or "").strip()
    quote = (fact.get("цитата") or "").strip()
    if not source or not quote:
        return False, "у факта нет источника или цитаты"

    name, _, anchor = source.partition("#")
    name = name.strip()
    anchor = anchor.strip()

    # Н2 ревью задачи 4: ЦИТАТУ без точного якоря (в т.ч. с хвостовой
    # пустой решёткой, «Тема 25468#») подтвердить нечем — до фикса сверка
    # в этом случае шла по всему телу заметки, а атрибуция бралась у
    # первого поста темы/записи блога независимо от того, в каком именно
    # посте цитата на самом деле встретилась (живой пример ревью: тема
    # 25468, цитата из поста 223272 получала подпись поста 186484).
    # Уточнение по ревью: ссылка «см. также» на источник целиком (факт БЕЗ
    # цитаты) сюда не доходит вовсе — её отсекает проверка выше («нет
    # источника или цитаты»); эта проверка — про цитату конкретно, не про
    # уместность ссылки как таковой, и рендерится ссылка другим кодом
    # (проходом 2), мимо `facts.py`.
    if not anchor:
        return False, "цитата требует точного якоря — сноска на источник целиком не подтверждает цитату"
    if not any(pattern.match(anchor) for pattern in _ANCHOR_FORMS):
        return False, "якорь «%s» не входит в закрытый список видов сносок (контракт зеркала §1)" % anchor

    if conn is not None:
        citable, reason = notes.citable_source(name, conn)
        if not citable:
            return False, reason

    path, reason = _resolve_note(mirror_root, name)
    if path is None:
        return False, reason

    text = notes.section(path, anchor)
    if text is None:
        return False, "якорь «%s» в заметке «%s» отсутствует" % (anchor, name)

    raw = normalize(text)
    clean = normalize(notes.citable(text))
    needle = normalize(quote)

    # Н6 ревью задачи 4: гейт проверяет только существование дословной
    # подстроки — двухсимвольная настоящая цитата («мм») с произвольной
    # сутью проходила бы как честный проверенный факт, потому что связь
    # цитаты и сути машине недоступна, а длина доступна. См. докстринг
    # MIN_QUOTE_CHARS — ПОЧЕМУ в знаках, а не в словах: однословные VIN/
    # артикулы/номера деталей — законные и ценные факты этого домена,
    # счётчик слов отверг бы их.
    if len(needle) < MIN_QUOTE_CHARS:
        return False, ("цитата короче минимальной длины (%d символов после схлопывания "
                        "пробелов) — недостаточно, чтобы быть проверяемым фактом" % MIN_QUOTE_CHARS)

    # Н11 ре-ревью задачи 6: см. докстринг MAX_QUOTE_NUMBER_UNITS — широкая
    # цитата с несколькими значениями сразу даёт индульгенцию любой их
    # перестановке в прозе. Проверяется здесь, а не только в
    # `pipeline.verify`: гейт прохода 1 — единственное место, где нечестную
    # цитату можно остановить ДО того, как она станет проверенным фактом
    # (тем же, который потом читает `pipeline.verify` через `check_one`).
    quote_values = notes.find_number_units(quote)
    if len(quote_values) > MAX_QUOTE_NUMBER_UNITS:
        return False, (
            "цитата содержит %d разных значений «число+единица» (предел %d, контракт "
            "зеркала §2) — широкая цитата подтверждает любую их перестановку в прозе"
            % (len(quote_values), MAX_QUOTE_NUMBER_UNITS))

    if needle in clean:
        return True, ""
    if needle in raw:
        return False, "цитата — текст генератора или чужого цитирования, а не автора"
    return False, "цитата не найдена дословно в источнике"


def check_all(facts: list[dict], mirror_root: Path, conn: sqlite3.Connection | None = None) -> dict:
    """Прогоняет `facts` через `check_one`; прошедшим присваивает `id`
    (`f1`, `f2`, … по порядку прохождения) и, если дан `conn`, дописывает
    `автор`/`дату` из базы (`_lookup_meta`) — ИЗ БАЗЫ, а не из ответа ИИ:
    иначе ИИ мог бы подписать чужую цитату правдоподобным, но не своим
    именем (следующая задача рендерит этими полями сноску, см. докстринг
    `_lookup_meta`). `conn` необязателен (программные вызовы/тесты без базы
    под рукой) — тогда ключи `автор`/`дата` у прошедших фактов попросту не
    добавляются, а не становятся `None` незапрошенно.

    Н3 ревью задачи 4: поля `автор`/`дата`, ЕСЛИ они пришли во входящем
    факте (проход 1 их присылать не должен, но формат JSON этого не
    запрещает), снимаются БЕЗУСЛОВНО, до ветки с `conn` — иначе безопасный
    режим (атрибуция из базы) был бы не режимом по умолчанию, а особым
    случаем: без `conn` `item = dict(fact)` переносил бы в проверенный
    факт любую подпись, присланную ИИ, непроверенной.
    """
    passed, dropped = [], []
    for fact in facts:
        ok, reason = check_one(fact, mirror_root, conn)
        if ok:
            item = dict(fact)
            item.pop("автор", None)
            item.pop("дата", None)
            item["id"] = "f%d" % (len(passed) + 1)
            if conn is not None:
                author, date = _lookup_meta(item.get("источник", ""), conn)
                item["автор"] = author
                item["дата"] = date
            passed.append(item)
        else:
            dropped.append({"факт": fact, "причина": reason})
    return {
        "проверено": passed,
        "отброшено": dropped,
        "статистика": {"всего": len(facts), "прошло": len(passed), "отброшено": len(dropped)},
    }


# --- автор/дата из базы -----------------------------------------------------

# ISO-дата в начале строки: `posts.posted_at` («2014-10-11 12:00:00»),
# `threads.started_at` («2014-10-11»).
_ISO_DATE = re.compile(r"^(\d{4})-(\d{2})-(\d{2})")
# Дата уже в русском виде в начале строки: `blog_posts.posted_at`/
# `blog_comments.posted_at` («11.10.2014 12:00:00») — у блогов её так
# отформатировал парсер (задача 7 Ф2), в отличие от форума.
_RU_DATE = re.compile(r"^(\d{2}\.\d{2}\.\d{4})")


def _only_date(value: str | None) -> str | None:
    """Дата без времени, в формате footnote-спеки (`docs/контракт-зеркала.md`
    §1, «Razum, 11.10.2014») — НЕ то же преобразование, что `mirror._ru_dt`:
    та собирает дату-и-время для шапки поста в заметке («11.10.2014
    12:00:00»), эта — только дату для сноски и умеет оба сырых формата,
    которые реально лежат в трёх таблицах (форум/темы — ISO, блоги — уже
    русский с временем), а не один.
    """
    if not value:
        return None
    m = _ISO_DATE.match(value)
    if m:
        y, mo, d = m.groups()
        return "%s.%s.%s" % (d, mo, y)
    m = _RU_DATE.match(value)
    if m:
        return m.group(1)
    return value


def _lookup_meta(source: str, conn: sqlite3.Connection) -> tuple[str | None, str | None]:
    """Автор и дата факта — ИЗ БАЗЫ по номеру поста/комментария из якоря,
    не из ответа ИИ.

    Три раздела зеркала несут это по-разному:
    - форум: `posts.author`/`posted_at` по `mid` из якоря `#Пост <MID>`,
      ДОПОЛНИТЕЛЬНО сверенному с `tid` из имени заметки (Н8 ревью задачи
      4 — `mid` первичный ключ и сам по себе уникален глобально, но
      проверка не должна держаться только на этом свойстве схемы: если
      имя заметки и реальная тема поста когда-нибудь разойдутся, запрос
      без `tid` молча вернул бы автора чужой темы; с `tid` — `(None,
      None)`, тот же класс несверенной перекрёстной связи, что в Ф2);
      анкор без якоря `#Пост <MID>` сюда не доходит вовсе — `check_one`
      (Н2 того же ревью) отвергает цитату без точного якоря до того, как
      факт мог бы попасть в `check_all`/`_lookup_meta`;
    - блог: `blog_posts.author`/`posted_at` (якорь `#Запись`) или
      `blog_comments.author`/`posted_at` по `#Комментарий <N>` — комментарий
      несёт СВОИ автора и дату, отдельные от записи;
    - FAQ: настоящего автора и даты НЕТ — вопрос/ответ базы знаний, а не
      реплика форумчанина. У записи есть только `snapshot_ts` — момент,
      когда её СНЯЛ краулер, а не когда написали; подставить его в «дату»
      сноски значило бы приписать записи чужую (архивную) дату как будто
      авторскую — обман того же рода, для защиты от которого затеян
      проект. Поэтому FAQ всегда даёт `(None, None)`.
    """
    name, _, anchor = source.partition("#")
    name = name.strip()
    anchor = anchor.strip()

    m = _NOTE_THEME.match(name)
    if m:
        pm = _ANCHOR_POST.match(anchor)
        if not pm:
            # Оборонительный возврат, не падение: у факта, прошедшего
            # `check_one`, якорь темы всегда «Пост <MID>» (единственная
            # форма из закрытого списка, которую реально несёт заметка
            # темы) — сюда попадаем только при прямом вызове в обход
            # `check_all`.
            return None, None
        row = conn.execute("SELECT author, posted_at FROM posts WHERE mid = ? AND tid = ?",
                            (int(pm.group(1)), int(m.group(1)))).fetchone()
        if not row:
            return None, None
        return row[0], _only_date(row[1])

    if _NOTE_FAQ.match(name):
        return None, None

    m = _NOTE_BLOG.match(name)
    if m:
        blog, post_id = m.group(1), int(m.group(2))
        cm = _ANCHOR_COMMENT.match(anchor)
        if cm:
            row = conn.execute(
                "SELECT author, posted_at FROM blog_comments "
                "WHERE blog = ? AND post_id = ? AND comment_id = ?",
                (blog, post_id, int(cm.group(1)))).fetchone()
        else:
            row = conn.execute("SELECT author, posted_at FROM blog_posts WHERE blog = ? AND post_id = ?",
                                (blog, post_id)).fetchone()
        if not row:
            return None, None
        return row[0], _only_date(row[1])

    return None, None
