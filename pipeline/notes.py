# альтернатив), только в обратную сторону: КОРОТКАЯ форма без пробела
# перехватила бы разбор у ЦЕЛОГО слитного слова.
_add_unit_synonyms("тыс.км", "тыкм")

# Составные виды из `_COMPOUND_UNITS`, обёрнутые в `^(?:...)$` для ПОЛНОГО
# совпадения — нужны `_is_recognized_unit` ниже, отдельно от их роли в
# `_UNIT` (там они участвуют в разборе позиции внутри большего текста, а
# здесь проверяют «токен ЦЕЛИКОМ выглядит как составная форма»). Строится
# из ТОГО ЖЕ тьюпла программно — единственный источник знания о формах
# составных единиц, а не второй, переписанный вручную список (тот же
# принцип, что у `_templated`/`GENERATOR_PATTERNS` в другом месте модуля).
_COMPOUND_UNIT_WHOLE = tuple(
    re.compile(r"^(?:%s)$" % pattern, re.IGNORECASE) for pattern in _COMPOUND_UNITS)


def _is_recognized_unit(token: str) -> bool:
    """Дефект 8 (пилот статей): решает, опознан ли `token` КАК единица
    измерения — а не «есть ли он в списке разрешённого». Источники
    опознания — те же три, что уже существуют в модуле для других целей,
    без НОВОГО списка единиц:

    1. Символ (`_UNIT_SYMBOL` — `%`, `°`, `°C`, `"`, `′` и т.п.):
       структурно не может совпасть со словом прозы, опознаётся всегда;
    2. Одиночная прописная буква (Н19: «В», «А», «К» — Кельвин/Вольт/
       Ампер) — тот же регистровый признак, что уже разводит эти буквы
       от предлогов/союзов;
    3. Составная форма ЦЕЛИКОМ (`_COMPOUND_UNIT_WHOLE` — множитель+единица,
       «л.с.», «куб.<единица>», «<единица>/<единица>» или «·», «к ом») —
       опознаётся по СТРУКТУРЕ, без требования, чтобы обе половинки ТАКЖЕ
       были в таблице синонимов по отдельности (иначе «об/мин» само не
       прошло бы — «об» никогда не регистрировался отдельно, хотя пара
       целиком опознана ре-ревью Н1 сканом корпуса);
    4. Каноническая форма — КЛЮЧ или ЗНАЧЕНИЕ в `_UNIT_SYNONYMS` (список
       единиц, которые кто-то когда-то сканировал и подтвердил на живом
       корпусе — Н23/Н24 и дефект 8 категория 2, а не придуманный с нуля).

    Если токен не подходит НИ ПОД ОДИН источник — он НЕ единица измерения
    по умолчанию (см. `_classify_unit`, где результат становится "soft"),
    а не наоборот, как было до дефекта 8. Список источников — закрытый и
    расширяется тем же способом, что таблица синонимов (скан корпуса,
    частоты, проверка коллизий), а не подгонкой под конкретное слово.
    """
    if re.fullmatch(_UNIT_SYMBOL, token, re.IGNORECASE):
        return True
    if _is_strict_single_letter_exception(token):
        return True
    if any(p.fullmatch(token) for p in _COMPOUND_UNIT_WHOLE):
        return True
    canon = _canon_unit(token)
    return canon in _UNIT_SYNONYMS or canon in _UNIT_SYNONYMS.values()


def _unit_identity(unit: str) -> str:
    """Итоговый ключ идентичности единицы — общая функция для (потенциально)
    составного вида «множитель+единица» и обычной единицы, единственное
    место, где `find_number_units` решает, что считать «той же» единицей
    (два потребителя одного знания обязаны ходить одной функцией).

    Вызывается ТОЛЬКО для `unit`, для которого `_classify_unit(unit) is
    None` (реальная единица измерения, не служебная/мягкая) — это условие
    уже проверил вызывающий код (`_extract_candidates`/`cls is not None`
    в `find_number_units`), поэтому если `_MULT_UNIT_SPLIT` совпал, гарантия
    классификации означает, что ОСТАТОК после множителя — тоже настоящая
    единица (см. рекурсию в `_classify_unit`), а не случайный кусок прозы.

    Составной вид («150 тысяч км») даёт ключ множителя (`_mult_canon`,
    нормализует написание множителя) + ключ остатка — САМ остаток тоже
    проходит через свёртку синонимов (`_UNIT_SYNONYMS`, Н23/Н24), поэтому
    «5 тысяч километров» и «5 тыс. км» дают один и тот же составной ключ,
    а не новую версию той же болезни на уровень выше (Н25 ре-ревью)."""
    m = _MULT_UNIT_SPLIT.match(unit)
    if m:
        rest_canon = _canon_unit(m.group("rest"))
        rest_canon = _UNIT_SYNONYMS.get(rest_canon, rest_canon)
        return _mult_canon(m.group("mult")) + rest_canon
    canon_unit = _canon_unit(unit)
    # Н23 ре-ревью: сокращение и слово целиком — одна и та же единица для
    # читателя, но разные ключи без свёртки (`_UNIT_SYNONYMS`) — см.
    # докстринг таблицы выше про то, почему это единственный оправданный
    # список в модуле.
    return _UNIT_SYNONYMS.get(canon_unit, canon_unit)


def find_number_units(text: str) -> set[tuple[str, str]]:
    """Числа с единицами измерения в `text`, канонизированные для сравнения.

    Симметричная функция — общий потребитель `pipeline.facts` (потолок
    числа значений в одной цитате, Н11 ре-ревью) и `pipeline.verify`
    (проверка 5): применяется и к прозе, и к цитате сноски ОДНИМ и тем же
    кодом, а не двумя копиями одного правила — иначе они разойдутся молча
    (тот же урок Ф2, что и у `normalize_spaces`).

    Диапазон `10-12 мм` (или с типографским тире) даёт ДВЕ пары —
    `("10","mm")` и `("12","mm")`, каждая обязана найтись отдельно (бриф
    задачи 6). Число, за которым идёт служебное слово/месяц/`wd` (см.
    `_STRICT_EXCLUSIONS`), не извлекается вовсе. Число рядом с
    количественным существительным домена (год, разы, деньги — см.
    `_SOFT_QUANTITY_NOUNS`) тоже НЕ становится парой «число+единица» — но
    не пропадает бесследно, а идёт в `find_quantity_claims` (Н16 ре-ревью).
    Множитель БЕЗ единицы за ним («150 тысяч») — туда же (Н25 ре-ревью):
    множитель — не единица измерения, а число само по себе значимо.
    """
    found: set[tuple[str, str]] = set()
    for numbers, unit, cls in _extract_candidates(text):
        if cls is not None:
            continue
        canon_unit = _unit_identity(unit)
        for num in numbers:
            found.add((num, canon_unit))
    return found


def find_quantity_claims(text: str) -> set[str]:
    """Голые числа рядом с «мягко» исключённым количественным
    существительным домена (год, лет, раз, шт, месяц, человек, деньги —
    `_SOFT_QUANTITY_NOUNS`) — Н16 ре-ревью задачи 6.

    В отличие от `find_number_units`, единица здесь ВООБЩЕ не участвует в
    сравнении: возвращается только канонизированное число. Раньше (первый
    вариант списка исключений) число, за которым стоит исключённое слово,
    не проверялось НИКАК — «Восьмой символ... означает 1998 год» проходило
    бы даже при том, что источник называет 1992. Само число — часто
    значимый факт домена (год выпуска — 8-й символ VIN), и его подмену
    обязан ловить `pipeline.verify`, сверяя с цитатой сноски этого
    утверждения ту же голую строку числа (без требования, чтобы рядом было
    слово «год» — его, в отличие от единицы измерения, автор источника мог
    и не написать).
    """
    claims: set[str] = set()
    for numbers, unit, cls in _extract_candidates(text):
        if cls != "soft":
            continue
        claims.update(numbers)
    return claims


# Денежный/множительный суффикс, приклеенный к числу без пробела («300р»
# — живая находка пилота статей, Тема 16109#Пост 306303: «ценик 300р»;
# «70тык» — дефект 7, сленговое «тысяча» без единицы, глухо приклеенное к
# числу; «5млн» — тот же класс для стандартного множителя).
# `find_bare_numbers` ищет число БЕЗ КАКОГО БЫ ТО НИ БЫЛО требования к
# соседнему слову (контракт §1: «8 - Год выпуска (С-1992)») — и именно
# поэтому вообще запрещает букву сразу после числа (`_NOT_LETTER_AHEAD`):
# без запрета цифровой хвост VIN/артикула читался бы как самостоятельное
# число. Деньги и множитель — исключение ИЗ ЭТОГО запрета, а не отмена
# его: те же сокращения, что уже перечислены в `_QUANTITY_NOUNS` (руб/р/тр
# — деньги) и в `_MULT` (тыс/тыщ/млн/млрд — стандартный множитель, тот же
# ЗАКОНЧЕННЫЙ и короткий список, что уже используется в разборе диапазонов
# и составных единиц, не второй переписанный список), плюс «тык» (дефект
# 7 — сленговое «тысяча», не входит в `_MULT` по отдельной причине, см.
# докстринг синонима «тыс.км»/«тыкм» выше). Разрешены сразу после числа
# без пробела, и ТОЛЬКО они — общего снятия запрета на букву это не
# открывает (VIN/артикул остаются отклонены). Требует границы СРАЗУ после
# суффикса (не быть началом другого, более длинного слова —
# «300рублика» не подходит целиком).
_QUANTITY_SUFFIX_GLUED = r"(?:%s|(?:руб|тр|р|тык)\.?)(?![A-Za-zА-Яа-яЁё0-9])" % _MULT
_NOT_LETTER_AHEAD_OR_QUANTITY = r"(?:%s|(?=%s))" % (_NOT_LETTER_AHEAD, _QUANTITY_SUFFIX_GLUED)
_BARE_NUMBER = re.compile(
    r"%s(?:%s|%s)%s" % (_NOT_LETTER_BEHIND, _FRACTION, _NUM, _NOT_LETTER_AHEAD_OR_QUANTITY),
    re.IGNORECASE)


def find_bare_numbers(text: str) -> set[str]:
    """Все отдельно стоящие числа `text`, канонизированные, БЕЗ КАКОГО БЫ
    ТО НИ БЫЛО требования к соседнему слову (Н16 ре-ревью — сторона
    ИСТОЧНИКА). Нужна затем, что `find_quantity_claims` требует рядом
    количественное существительное («год», «раз») — а в ЦИТАТЕ источника
    того же числа это слово может не быть вовсе: контракт зеркала §1
    описывает год выпуска VIN как «8 - Год выпуска (С-1992)» — число внутри
    скобок, без единого слова «год» рядом. Число ищется, а не единица —
    те же защиты от идентификаторов (`_NOT_LETTER_BEHIND`/`_AHEAD`), что и
    у `find_number_units`, чтобы не выхватить цифровой хвост VIN/артикула.
    """
    text = _strip_number_noise(text)
    return {_canon_number(m.group(0)) for m in _BARE_NUMBER.finditer(text)}


def normalize_spaces(text: str) -> str:
    """Схлопывает любую пробельную последовательность (пробел, табуляция,
    одинарный/двойной перенос строки) в один пробел и обрезает по краям.

    Живёт здесь, а не рядом с вызывающим кодом, потому что у неё минимум
    два независимых потребителя одного факта — «представления одного и
    того же текста в разных источниках расходятся пробелами, а не
    смыслом»: `pipeline.faq_dedup` (два движка форума разбивают абзацы
    ответа по-разному — `\\n` у старого движка там, где у Bitrix `\\n\\n`)
    и дословная проверка цитат Ф3 (задача 4) — тот же класс расхождения,
    что уже задокументирован как системный между `posts.text` и
    `posts.markdown` (Global Constraint №1, 56% постов). Ревью задачи 1
    поймало живой пример: `find_duplicates` сравнивал сырую строку
    `in`-подстрокой и пропустил два настоящих дубля (FAQ старый 114/155)
    только из-за разных пробелов. Два потребителя одного правила обязаны
    ходить одной функцией — иначе разойдутся молча, как разошлись
    `sync_to_db`/`local_path` в Ф2.
    """
    return re.sub(r"\s+", " ", text or "").strip()


# --- границы абзаца (Н11 ре-ревью задачи 6, второй раунд) -------------------
#
# Первая версия правки Н11 (см. `facts.MAX_QUOTE_NUMBER_UNITS`, коммит
# 06d7c457) считала числа по ВСЕЙ цитате — и это оказалось решением по
# рассуждению, не по замеру: живой корпус (разделы форума 17+19, 625
# постов) показал, что 4,35% абзацев и 1,73% предложений несут БОЛЬШЕ двух
# разных «число+единица» В ОДНОМ АБЗАЦЕ ОДНОГО АВТОРА — температурная
# кривая датчика, диапазоны сопротивления по группам производителей,
# диагностические пороги напряжения. Это не подделки, это ровно то, ради
# чего домен и техстатьи существуют — счётчик по всей цитате резал
# законный материал c той же безжалостностью, что и подделку.
#
# Настоящая опасность (Н11) не в ЧИСЛЕ значений, а в СКЛЕЙКЕ: нормализация
# пробелов (обязательна, Global Constraint фазы №1 — перенос строки не
# подделка) схлопывает границу МЕЖДУ абзацами в тот же один пробел, что и
# перенос строки ВНУТРИ одной мысли автора, и в результате цитата, честно
# дословно найденная в тексте целиком, может быть на самом деле склеена из
# НЕСКОЛЬКИХ независимых абзацев источника — только тогда переставленные
# местами значения остаются незамеченными (живой пример — Тема
# 19033#Пост 160401, четыре абзаца, четыре кузова, четыре разных клиренса).
#
# Поэтому правило (второй раунд, по требованию тимлида): потолок числа
# значений применяется ТОЛЬКО к цитате, которая НЕ умещается ни в одном
# ОДНОМ абзаце источника целиком — то есть пересекает границу абзаца.
# Цитата внутри одного абзаца — слова ОДНОГО автора в ОДНОМ непрерывном
# высказывании — проходит с любым числом значений: перечень (кривая
# датчика по температуре, диапазон по группам) для неё легален по
# определению, переставлять в нём нечего, склейки не было.
PARAGRAPH_SPLIT = re.compile(r"\n\s*\n")


def quote_crosses_paragraph(quote: str, source_text: str) -> bool:
    """Истина, если дословно найденная `quote` НЕ умещается целиком ни в
    одном ОДНОМ абзаце `source_text` — то есть склеена нормализацией из
    нескольких. Вызывать только когда дословность `quote` в `source_text`
    ЦЕЛИКОМ уже подтверждена (иначе результат `True` неотличим от «цитаты
    нет вовсе»); `source_text` — уже пропущенный через `citable()` текст
    секции (генераторный мусор не должен считаться «своим» абзацем).
    """
    needle = normalize_spaces(quote)
    return not any(needle in normalize_spaces(p) for p in PARAGRAPH_SPLIT.split(source_text))
