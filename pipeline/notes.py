#: и в ОБОИХ местах была одна и та же ошибка порядка альтернатив: короткое
#: «тыс\.?» стояло ПЕРЕД длинным «тысяч[а-я]*», а `|`-альтернация Python
#: берёт ПЕРВУЮ подошедшую ветку, а не самую длинную. На вход «тысяч»
#: короткая ветка «тыс\.?» откусывала только «тыс» (без точки), а
#: оставшееся «яч» доставалось следующему по цепочке `_UNIT_WORD` как
#: «единица» — итоговый «составной» токен ВЫГЛЯДЕЛ как «тысяч» целиком
#: (три части «тыс»+«»+«яч» просто склеились обратно в исходную строку),
#: но НАСТОЯЩАЯ единица после множителя (третье слово, «км»/«рублей») в
#: этой цепочке уже не участвовала — регэксп заканчивался на границе
#: пробела после «яч». Отсюда живая подделка Н25: «150 тысяч км» и «150
#: тысяч рублей» канонизировались в один и тот же вырожденный ключ
#: «tysyach» (без единицы вовсе) — не только они, а вообще ЛЮБАЯ единица
#: за множителем «тысяч»/«тыщ»/«млн»/«млрд» (в отличие от «тыс.», где
#: ветка `тыс\.?` подходила сразу и целиком, единица не терялась).
#:
#: Порядок альтернатив ниже — от ДЛИННОЙ буквальной формы к короткой,
#: поэтому альтернация больше не может остановиться на префиксе одного
#: варианта, не долистав до конца слова: «тысяч[а-я]*» ловит «тысяча»/
#: «тысячи»/«тысяч»/«тысячах»/опечатки вида «тысячь» ОДНИМ классом
#: `[а-я]*` (закрытый класс букв алфавита, не перечень конкретных
#: окончаний), «тыщ[а-я]*» — тот же приём для разговорного варианта
#: («тыщ»/«тыщи»/«тыщах»), «тыс\.?» — короткое сокращение (с точкой и
#: без), только ПОСЛЕ длинных форм, чтобы не откусить у них голову.
#: Миллион/миллиард — тот же приём.
_MULT = (r"(?:тысяч[а-я]*|тыщ[а-я]*|тыс\.?"
         r"|миллиард[а-я]*|млрд\.?|миллион[а-я]*|млн\.?)")
#: Множитель БЕЗ единицы за ним («продал за 150 тысяч») — весь токен
#: целиком совпадает с одним из написаний множителя.
_MULT_ONLY = re.compile(r"^%s$" % _MULT, re.I)
#: Множитель С единицей за ним («150 тысяч км») — единица (`rest`)
#: проверяется классификацией ОТДЕЛЬНО (см. `_classify_unit`), а не
#: заглатывается регэкспом вслепую: без этой проверки жадный `_UNIT_WORD`
#: после множителя приклеил бы к нему СЛЕДУЮЩЕЕ СЛОВО ПРОЗЫ, будь то
#: реальная единица или случайный предлог/союз («5 тысяч и» — «и» тут не
#: единица, а продолжение предложения), и такой мусорный композит либо
#: не совпал бы ни с чем (ложный шум), либо, что хуже, canon_word от него
#: мог случайно попасть в исключение и молча потерять число.
_MULT_UNIT_SPLIT = re.compile(r"^(?P<mult>%s)\s?(?P<rest>.+)$" % _MULT, re.I)


def _mult_canon(raw_mult: str) -> str:
    """Нормализует НАПИСАНИЕ множителя (сколько бы их ни было —
    «тыс»/«тыс.»/«тысяч»/«тыщ» и т.д.) к ОДНОМУ ключу, тем же приёмом,
    что таблица синонимов единиц (Н23/Н24): иначе «5 тысяч км» и «5 тыс.
    км» несли бы разные составные ключи (`tysyachkm` и `tyskm`), и статья
    с одним написанием не подтвердила бы цитату с другим — тот же класс
    ошибки, что чинили для целых единиц, только теперь внутри множителя.
    Ключ `tys` выбран НЕ произвольно — это уже существующий канонический
    ключ старого («тыс.»-only) поведения, и существующие тесты/данные на
    нём завязаны."""
    w = raw_mult.lower()
    if w.startswith(("тысяч", "тыщ", "тыс")):
        return "tys"
    if w.startswith(("миллиард", "млрд")):
        return "mlrd"
    if w.startswith(("миллион", "млн")):
        return "mln"
    raise AssertionError("раз _MULT совпал, обязана подойти одна из веток: %r" % raw_mult)


def _is_strict_single_letter_exception(token: str) -> bool:
    """Н19 ре-ревью (регресс, серьёзный): `_canon_unit` приводит регистр
    ДО проверки исключений, поэтому однобуквенное служебное слово («в»,
    «а», «с» — предлоги/союз) неотличимо от однобуквенной ЕДИНИЦЫ
    измерения («В» — вольт, «А» — ампер) после `.lower()` — обе дают один
    и тот же канонический ключ. Результат регресса: «напряжение 12 В»,
    «ток 5 А» перестали извлекаться вовсе (162 и 113 живых вхождений
    форума), а живая подделка (заниженный вдевятеро порог диагностики,
    «< 0,1 В» источника против «< 0,9 В» статьи) проходила бы молча.

    Регистр в русском тексте ЭТУ РАЗНИЦУ и несёт: единицу пишут ПРОПИСНОЙ
    (В, А), предлог/союз/частицу — строчной. Поэтому регистр однобуквенного
    токена РЕШАЕТ: строчная буква — исключение держится (предлог/союз),
    ПРОПИСНАЯ — не исключение (вероятно, единица). Многобуквенные слова
    этой коллизии не подвержены (у них нет однобуквенных единиц-омонимов
    среди служебных слов) — правило узкое, не общее «регистр всегда важен».
    """
    return len(token) == 1 and token.isupper()


def _classify_unit(token: str) -> str | None:
    """`"strict"` (не проверяется вовсе — служебное слово/месяц/«wd»),
    `"soft"` (не единица, но число проверяется голым — количественное
    существительное домена) или `None` (настоящая единица измерения)."""
    word = _canon_word(token)
    if word in _STRICT_EXCLUSIONS and not _is_strict_single_letter_exception(token):
        return "strict"
    if word in _SOFT_QUANTITY_NOUNS:
        return "soft"
    # Множитель БЕЗ единицы за ним («продал за 150 тысяч») — число само по
    # себе значимый факт (как год/цена — `_SOFT_QUANTITY_NOUNS`), но
    # множитель — не единица измерения; поэтому "soft", а не strict и не
    # None (Н25 ре-ревью). Проверяется по СЫРОМУ `token`, а не по `word`:
    # `word` уже вырезал пробел между словами составного вида («тысяч км»
    # -> «тысячкм»), и после этого жадный `[а-я]*` внутри `_MULT` не
    # отличит настоящую многобуквенную единицу, слипшуюся после вырезки
    # пробела, от опечатки в самом множителе — «тысячкм» целиком выглядел
    # бы как «тысяч» + ещё две «лишние» кириллические буквы одного и того
    # же класса. У сырого `token` пробел на месте, и `_MULT` (без пробела
    # внутри своих альтернатив) через него пройти не может.
    if _MULT_ONLY.fullmatch(token):
        return "soft"
    # Множитель С единицей за ним («150 тысяч км») — единица после
    # множителя классифицируется РЕКУРСИВНО САМА ПО СЕБЕ (Н25 ре-ревью):
    # если это служебное слово/случайный кусок прозы, множитель остаётся
    # "soft" (число значимо само по себе, единицы измерения тут нет и не
    # было); если это тоже "мягкое" исключение (деньги — «тыс. руб»),
    # результат тот же; и только если это НАСТОЯЩАЯ единица измерения,
    # composite становится ЕДИНИЦЕЙ (`None`) — сам ключ строит
    # `find_number_units` (`_mult_canon` + канон единицы, включая
    # свёртку `_UNIT_SYNONYMS`), здесь важна только классификация.
    m = _MULT_UNIT_SPLIT.match(token)
    if m:
        rest_cls = _classify_unit(m.group("rest"))
        return None if rest_cls is None else "soft"
    # Дефект 8 (пилот статей): ДО этой строки любой токен, не попавший ни
    # в одно исключение выше, автоматически становился НАСТОЯЩЕЙ единицей
    # (`None`) — тот самый открытый класс, о котором предупреждает
    # докстринг модуля («обычное слово... МОГУТ ложно распознаться как
    # число с неизвестной «единицей»... цена такой находки мала»). Прогноз
    # был верным для форума (мало), но НЕВЕРНЫМ для статей: на живой
    # статье пилота («Износ двигателей») из 27 замечаний больше двадцати
    # оказались словами прозы после числа («живучи», «составлял», «слой»,
    # «летом», «зимой» — ни одно не единица измерения), потому что прозу
    # пишет ИИ по фактам, а не форумчанин своим языком, и совпадений
    # «число + случайное слово» на статье закономерно больше.
    #
    # Начиная с этой правки — токен, не опознанный НИ ОДНИМ из источников
    # `_is_recognized_unit` (таблица синонимов, символ, составная форма),
    # больше не единица измерения по умолчанию: он "soft" — то же самое
    # мягкое поведение, что уже есть у количественных существительных
    # домена (год/деньги/штуки) и у голого множителя. Число ВСЁ РАВНО
    # обязано найтись в цитате (`find_bare_numbers` в `verify.py`) — не
    # ослабление проверки числа, а снятие требования, чтобы рядом стояло
    # ИМЕННО ЭТО слово. Подмена настоящей единицы продолжает ловиться:
    # опознанные единицы (мм против см, оба в таблице синонимов) остаются
    # `None` и сверяются жёстко, как раньше.
    return None if _is_recognized_unit(token) else "soft"


_UNIT_WORD = r"[A-Za-zА-Яа-яЁё]{1,20}"
# Составные виды — перечислены явно (см. докстринг выше, почему не общим
# паттерном «слово.слово»): множитель «тыс.»/«тысяч» + единица, «л.с.»
# (лошадиные силы), «куб.<единица>» (куб.см), «<единица>/<единица>»,
# «<единица>·<единица>» (об/мин, кгс·м) и «к Ом» (килоом с пробелом внутри —
# см. комментарий у последнего элемента тьюпла).
_COMPOUND_UNITS = (
    # Множитель — один источник знания с `_classify_unit`/`_mult_canon`
    # (`_MULT`, см. докстринг там про Н25 и баг порядка альтернатив).
    r"%s\s?%s" % (_MULT, _UNIT_WORD),
    r"л\.\s?с\.?",
    r"куб\.\s?%s" % _UNIT_WORD,
    r"%s[/·]%s" % (_UNIT_WORD, _UNIT_WORD),
    # Живая находка пилота статей (Тема 14487#Пост 87648): «3,0 К Ом» —
    # килоом, набранный с пробелом между приставкой «к» (кило-) и «Ом»,
    # вместо привычного слитного «кОм». Без этой ветки `_UNIT_WORD` (не
    # умеет переходить через пробел) захватывал только одиночную «К», и
    # `_canon_unit` не успевала снять пробел — она чистит уже ПОЙМАННЫЙ
    # токен, а токеном была только буква «К» без «Ом» вовсе. Указана явно
    # (не общим «буква + пробел + буквы» — это склеило бы предлог «к» с
    # ЛЮБЫМ следующим словом прозы, «к отлично» в это число тоже включив),
    # без `re.IGNORECASE` в самой ветке — регистр не имеет значения (флаг
    # уже стоит на компиляции `_RANGE`/`_SINGLE` целиком), а вот граница
    # «дальше не буква» (`_NOT_LETTER_AHEAD`, общая для всего `_UNIT`) —
    # ровно то, что отсекает «к об-» и любое другое слово, которое просто
    # НАЧИНАЕТСЯ на «ом», не будучи им целиком (проверено на живом корпусе:
    # ни одного случая «к ом<буква>» на 48 689 постов, только 5 живых «к
    # Ом»/«К Ом», все — сопротивление в килоомах).
    r"к\s?ом",
)
# Единицы-символы: проценты, градус (с необязательной буквой шкалы),
# дюймовые/минутные штрихи (`3/16"`, ASCII- и типографский вид). У них нет
# буквы на конце — общая граница `\b` ниже для них не годится совсем (`\b`
# требует стороны \w/не-\w, а по обе стороны от `"`/`%` букв нет), поэтому
# конец единицы проверяется негативным просмотром вперёд «дальше не буква»,
# а не `\b` (см. `_UNIT`).
_UNIT_SYMBOL = r'(?:%|°[A-Za-zА-Яа-яЁё]?|["\'″′])'
_UNIT = "(?:%s)" % "|".join(list(_COMPOUND_UNITS) + [_UNIT_WORD, _UNIT_SYMBOL])
# Дальше НЕ должно идти ни буквы, ни цифры — не только `\b`-эквивалент для
# буквенных единиц (у единиц-символов вроде `"`/`%` `\b` не работает вовсе:
# по обе стороны от них нет `\w`), но и защита от артикулов/VIN
# («22611AD982»): без цифрового запрета «22611» + «AD» ошибочно читалось
# бы как число с единицей «AD», хотя это один слитный идентификатор.
_NOT_LETTER_AHEAD = r"(?![A-Za-zА-Яа-яЁё0-9])"
# ...и ПЕРЕД числом не должно быть ни буквы, ни цифры — та же дыра с другой
# стороны: VIN `JF1GDDLF37G076103` содержит цифровой хвост `076103`,
# которому непосредственно ПРЕДШЕСТВУЕТ буква («G076103»); без запрета
# слева `076103` читался бы как самостоятельное число, и «076103 на форуме»
# (обычный предлог сразу после числа) ошибочно давал бы число с «единицей»
# «на» — предлог, а не единица измерения, просто оказался внутри
# идентификатора, а не после настоящего числа.
_NOT_LETTER_BEHIND = r"(?<![A-Za-zА-Яа-яЁё0-9])"

#: Внутренний пробел числа-с-разрядами («10 000») — ТОЛЬКО пробельные
#: СИМВОЛЫ разделителя разрядов (обычный, неразрывный, узкий неразрывный),
#: а не любой `\s` (перенос строки, табуляция). Находка структурного
#: класса (не находка-список): `\s` внутри старого `_NUM` жадно проглатывал
#: и перевод строки, и ДВОЙНОЙ перевод строки (границу абзаца/предложения)
#: как «пробел внутри числа» — «23714\n\nИ» читалось как ОДНО число
#: «23714» с «единицей» «И», хотя на самом деле это конец одного абзаца и
#: заглавная буква, начинающая совсем другое предложение (живая находка —
#: буква после точки в НАЧАЛЕ предложения не единица НИКОГДА, независимо
#: от того, какая это буква, а не только «в»/«а»/«с» из списка). После
#: сужения до собственно пробела `_SINGLE`/`_RANGE` попросту не могут
#: дотянуться через абзацную/предложенческую границу до следующего слова —
#: это и есть проверка «по контексту», а не по перечню букв.
_NUM_SPACE = "   "
_NUM = r"\d[\d%s]*(?:[.,]\d+)?" % _NUM_SPACE
_FRACTION = r"\d+\s*/\s*\d+"
# ASCII-дефис и типографские тире (Н8: `7–4 мм` с длинным тире не ловился).
_DASH = r"[-‐-―−]"
# Разделитель диапазона через ДВЕ точки («3300..3500 об/мин» — живая
# находка пилота статей, Тема 16109#Пост 104598: «обороты холостого хода
# 3300..3500 об/мин» — обычная форма записи диапазона на форуме, не опечатка
# и не десятичная дробь). Ровно ДВЕ точки, не «две и более» (`(?!\.)`
# запрещает третью подряд) — сканирование живого корпуса (48 689 постов)
# развело эти случаи однозначно: у РОВНО двух точек 7 живых вхождений, и
# ВСЕ семь — настоящий диапазон (давление, обороты, температура, протектор
# шины); у трёх точек и больше — 109 вхождений, и почти все это НЕ
# диапазон, а типографский эллипсис, усекающий длинную markdown-ссылку/URL/
# координату («55.76054...01929», «t1151413...» — визуальное «текст
# длинный, вот кусок его начала и конца», а не значение). Расширять до
# произвольного числа точек значило бы поймать URL-мусор вместо диапазона.
_RANGE_SEP = r"(?:%s|\.\.(?!\.))" % _DASH
_RANGE = re.compile(
    r"%s(?P<n1>%s)\s*%s\s*(?P<n2>%s)\s*(?P<unit>%s)%s"
    % (_NOT_LETTER_BEHIND, _NUM, _RANGE_SEP, _NUM, _UNIT, _NOT_LETTER_AHEAD),
    re.IGNORECASE)
_SINGLE = re.compile(
    r"%s(?P<num>%s|%s)\s?(?P<unit>%s)%s" % (_NOT_LETTER_BEHIND, _FRACTION, _NUM, _UNIT, _NOT_LETTER_AHEAD),
    re.IGNORECASE)

#: «30к», «14к руб», «5к-6к» — разговорное «тысяча», СЛИТНО с числом,
#: строчной буквой (Н25 ре-ревью: «"к" в значении тысячи, если
#: встречается» — встречается, 113 чистых живых вхождений на корпусе, все
#: слитно и все строчной). Отдельный проход, НЕ ветка внутри `_SINGLE`/
#: `_UNIT` — разбираемый признак здесь не буква сама по себе (её уже
#: занимает исключение предлога «к» и разведённая по регистру находка
#: Н19 — заглавная «К», Кельвин/кило-), а СЛИТНОСТЬ написания: пробела
#: между числом и «к» в этом значении не бывает никогда (иначе это
#: предлог, «еду к 5 часам»), и это ЕДИНСТВЕННЫЙ надёжный сигнал. Общая
#: цепочка `_RANGE`/`_SINGLE` этот признак не несёт (`_classify_unit`
#: получает только текст токена, не то, был ли перед ним пробел), поэтому
#: не встроено внутрь неё, а идёт отдельным сканированием с тем же
#: результатом контракта — числа-кандидата, помеченного `"soft"`
#: (значимо само по себе, единицей измерения не становится — тот же
#: контракт, что у бытового множителя «тысяч» без единицы за ним).
#: Специально БЕЗ `re.IGNORECASE` — прописная «К» (единственная неведомая
#: константе позиция: «4300К» температура Кельвина, «3,0 К Ом»
#: килоомы) не задета вовсе, поле различения то же, что у Н19: и
#: регистр буквы, и слитность написания одновременно, не только одно.
_ATTACHED_THOUSAND_K = re.compile(r"%s(?P<num>%s)к%s" % (_NOT_LETTER_BEHIND, _NUM, _NOT_LETTER_AHEAD))


def _extract_candidates(text: str) -> list[tuple[tuple[str, ...], str, str | None]]:
    """Все числовые кандидаты `text` (после `_strip_number_noise`) —
    список `(числа, единица-как-написана, классификация)`, классификация —
    результат `_classify_unit` (`None`/`"soft"`/`"strict"`). Диапазон даёт
    кортеж из ДВУХ чисел, одиночное — из ОДНОГО. Общее сканирование для
    `find_number_units` и `find_quantity_claims` (Н16 ре-ревью) — одна
    цепочка регэкспов на два потребителя, а не две копии одного разбора.
    """
    text = _strip_number_noise(text)
    out: list[tuple[tuple[str, ...], str, str | None]] = []
    spans: list[tuple[int, int]] = []
    for m in _RANGE.finditer(text):
        spans.append((m.start(), m.end()))
        cls = _classify_unit(m.group("unit"))
        out.append(((_canon_number(m.group("n1")), _canon_number(m.group("n2"))), m.group("unit"), cls))

    def _inside_range(pos: int) -> bool:
        return any(a <= pos < b for a, b in spans)

    for m in _SINGLE.finditer(text):
        if _inside_range(m.start()):
            continue
        cls = _classify_unit(m.group("unit"))
        out.append(((_canon_number(m.group("num")),), m.group("unit"), cls))

    # «30к» слитно (Н25 ре-ревью) — отдельный проход (см. докстринг
    # `_ATTACHED_THOUSAND_K`), не конкурирует с `_SINGLE` за один и тот же
    # кандидат: `_SINGLE` тоже находит эту пару («30», unit="к"), но
    # классифицирует «к» как служебное слово («strict», предлог) и
    # получившийся кандидат просто ИГНОРИРУЕТСЯ обоими потребителями —
    # этот проход добавляет РЯДОМ второй, «мягкий» кандидат на ТО ЖЕ
    # число, который потребители (в отличие от строгого) не отбрасывают.
    for m in _ATTACHED_THOUSAND_K.finditer(text):
        out.append(((_canon_number(m.group("num")),), "к", "soft"))
    return out


