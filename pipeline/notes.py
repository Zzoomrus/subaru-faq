"""Единственный способ прочитать то, на что указывает сноска.

Канон дословной проверки Ф2 (решение 30) — ТЕЛО ЗАМЕТКИ, не поле базы:
`posts.text` и `posts.markdown` расходятся у 27267 постов из 48689. Заметки
воспроизводятся байт-в-байт и физически являются целью сноски, значит они и
есть истина.

Секция кончается заголовком ЛЮБОГО уровня: в заметке темы посты размечены
`##### Пост <MID>`, но внутри поста может встретиться строка, начинающаяся
с `#` (в Ф1 таких нашлось 22-26, они экранированы генератором). Правило
«до следующего заголовка любого уровня» совпадает с тем, как секцию
понимает Obsidian, — а сноска адресует именно его.
"""
from __future__ import annotations

import re
from pathlib import Path

from pipeline import mirror, mirror_blog, mirror_faq

HEADING = re.compile(r"^(#{1,6})\s+(.+?)\s*$", re.M)


def _exact_line(literal: str) -> re.Pattern:
    """Регэксп для плейсхолдера-константы генератора, который всегда
    занимает ЦЕЛУЮ строку-абзац (`out.append(literal)` — своим элементом
    списка, между пустыми строками)."""
    return re.compile(r"^%s$" % re.escape(literal), re.M)


def _templated(template: str, placeholder: str, wildcard: str, whole_line: bool = False) -> re.Pattern:
    """Регэксп, собранный ИЗ шаблона генератора программно, а не
    перепечатанный сюда буквально: экранирует неизменные куски шаблона и
    вставляет `wildcard` там, где генератор подставляет переменную
    (`%s`/`%d`). Так текст живёт в одном месте — в генераторе, который его
    пишет, — и не может разойтись с тем, что здесь вычищается, если кто-то
    поправит формулировку в генераторе, забыв про очистку (находка 1
    ревью задачи 3: перечень из брифа уже отстал от генераторов на четыре
    плейсхолдера, потому что был перепечатан руками).
    """
    parts = template.split(placeholder)
    if len(parts) != 2:
        raise ValueError("шаблон %r должен содержать %r ровно один раз" % (template, placeholder))
    body_re = wildcard.join(re.escape(p) for p in parts)
    return re.compile(r"^%s$" % body_re, re.M) if whole_line else re.compile(body_re)


#: Строки, которые написал генератор зеркала, а не человек. Цитировать их
#: нельзя: проверка дословности прошла бы, подтвердив несуществующие слова.
#: Источник истины — сами генераторы (`mirror`/`mirror_faq`/`mirror_blog`):
#: их именованные константы-плейсхолдеры превращаются в регэкспы здесь, а
#: не переписываются буквально (ревью задачи 3, находки 1-3). Контрактный
#: тест `tests/test_notes.py::
#: test_every_generator_placeholder_literal_is_scrubbed_by_citable`
#: сканирует исходники трёх генераторов и падает, если там появится новый
#: плейсхолдер-константа, не покрытый ни одним паттерном ниже.
GENERATOR_PATTERNS: tuple[re.Pattern, ...] = (
    # Картинка не скачалась — пометка может стоять и посреди предложения
    # (docstring `mirror._missing_note`), поэтому без привязки к границам
    # строки.
    _templated(mirror.IMAGE_LOST_TEMPLATE, "%s", r"[^)]*"),
    # Вопрос/ответ/комментарий/тело записи пусты — плейсхолдер занимает
    # ЦЕЛУЮ строку-абзац во всех четырёх генераторах.
    _exact_line(mirror_faq.QUESTION_LOST),
    _exact_line(mirror_faq.ANSWER_LOST),
    _exact_line(mirror_blog.EMPTY_COMMENT),
    _exact_line(mirror_blog.BODY_LOST),
    # Историческая синонимия из брифа задачи 3: реального плейсхолдера с
    # ТАКИМ текстом ни один генератор не пишет (проверено на живом
    # корпусе — 0 совпадений), но тест `test_citable_drops_empty_
    # placeholders` требует его буквально, и вреда он не несёт (тест
    # `test_every_generator_placeholder_literal_is_scrubbed_by_citable`
    # проверяет полноту по факту написанного генераторами, эта строка в
    # его учёте не участвует и не обязана).
    re.compile(r"^\(пустой комментарий\)$", re.M),
    # Шапка поста/комментария: «*Автор · дата[ · #N]*». Матчим СТРУКТУРОЙ —
    # курсив целиком + разделитель + дата, — а не запретом `*` в имени:
    # форум цензурит часть ников звёздочками (находка 1 ревью: 6 живых
    # постов темы 24918, `*Svetik**** Насонова · ... · #23*` не матчился
    # старым `[^*\n]+`). Дата — надёжный якорь правой границы («звёздочка
    # + дата» само по себе не встречается в авторском тексте построчно —
    # проверено на живом корпусе, 181 строка вида `*...*` без даты, и все
    # они либо декоративный разделитель `***`, либо пометка «ответ на
    # комментарий» ниже, ни одна не авторский текст).
    re.compile(r"^\*.+? · \d{2}\.\d{2}\.\d{4}.*?\*$", re.M),
    # Пометка «ответ на комментарий №N» под шапкой комментария-ответа
    # (находка 2 ревью — генератор её пишет, старый список патернов не
    # знал о ней вовсе).
    _templated(mirror_blog.REPLY_MARKER_TEMPLATE, "%d", r"\d+", whole_line=True),
    # Вставка картинки — адрес файла, а не слова автора.
    re.compile(r"!\[\[[^\]]+\]\]"),
)


def body(path: Path) -> str:
    text = Path(path).read_text(encoding="utf-8")
    if text.startswith("---\n"):
        # Искать закрывающий `\n---\n` с позиции 0, не 4: у ВЫРОЖДЕННОГО
        # пустого frontmatter (`---\n---\n...`) ведущий `\n` закрывающей
        # строки стоит на позиции 3 — ровно перед прежней стартовой
        # позицией поиска, `find` его не видел, и frontmatter не срезался
        # вовсе (находка 5 ревью задачи 3). Ложного совпадения с ОТКРЫВАЮЩИМ
        # `---` это не создаёт: искомая подстрока начинается с `\n`, а перед
        # символом 0 файла никакого `\n` нет.
        end = text.find("\n---\n", 0)
        if end != -1:
            text = text[end + 5:]
    return text


def section(path: Path, anchor: str) -> str | None:
    text = body(path)
    matches = list(HEADING.finditer(text))
    for i, m in enumerate(matches):
        if m.group(2).strip() == anchor.strip():
            start = m.end()
            end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
            return text[start:end].strip("\n")
    return None


def citable(text: str) -> str:
    for pattern in GENERATOR_PATTERNS:
        text = pattern.sub(" ", text)
    return text


def normalize_spaces(text: str) -> str:
    """Схлопывает любую пробельную последовательность (пробел, табуляция,
    одинарный/двойной перенос строки) в один пробел и обрезает по краям.

    Живёт здесь, а не рядом с вызывающим кодом, потому что у неё минимум
    два независимых потребителя одного факта — «представления одного и
    того же текста в разных источниках расходятся пробелами, а не
    смыслом»: `pipeline.faq_dedup` (два движка форума разбивают абзацы
    ответа по-разному — `\\n` у старого движка там, где у Bitrix `\\n\\n`)
    и дословная проверка цитат Ф3 (задача 4) — тот же класс расхождения,
    что уже задокументирован как системный между `posts.text` и
    `posts.markdown` (Global Constraint №1, 56% постов). Ревью задачи 1
    поймало живой пример: `find_duplicates` сравнивал сырую строку
    `in`-подстрокой и пропустил два настоящих дубля (FAQ старый 114/155)
    только из-за разных пробелов. Два потребителя одного правила обязаны
    ходить одной функцией — иначе разойдутся молча, как разошлись
    `sync_to_db`/`local_path` в Ф2.
    """
    return re.sub(r"\s+", " ", text or "").strip()
