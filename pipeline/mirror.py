"""Генератор зеркала: заметка Markdown на каждую тему форума.

Формат заметки сложился из брифа задачи 7 и решений фазы; после итогового
ревью ветки (дефекты I1–I3) он переделан одним заходом. Кратко:

- Имя файла — `Тема <TID>.md`, без названия темы (переименование сломало бы
  сноски); название — только в `aliases`.
- Адрес поста — ЗАГОЛОВОЧНЫЙ якорь: заголовок ровно `##### Пост <MID>`,
  автор/дата/номер — строкой ниже. Ссылка `[[Тема 42335#Пост 391784]]`
  адресует весь пост до следующего заголовка. Прежний блочный якорь
  `^p<MID>` убран совсем: он адресовал ОДИН блок, то есть последний абзац
  поста, а многоабзацных постов 19140 из 48689 — сноска раскрывала бы хвост
  поста и молча (ссылка валидна, проверка зелёная, видно только глазами).
  Заголовок выбран текстом `Пост <MID>`, а не «автор · дата»: он уникален
  внутри заметки, стабилен при любом пере-рендере и не содержит символов
  `# | ^ : [[ ]]`, которые документация Obsidian называет ломающими ссылку
  (у ников форума такие символы встречаются).
- Раз якорь адресует весь пост, коллауты об утраченных картинках теперь
  ВНУТРИ секции поста — это осознанная смена прежнего «Решения 1»: пометки
  относятся именно к этому посту, и в сноске им место.
- Тело поста — `posts.markdown`, а не `posts.text` (дефект I1): цитаты
  остаются блокквотами (13775 постов с цитатами), ссылки — ссылками с
  адресом (в плоском тексте URL терялся примерно у трети ссылок).
  `posts.text` остаётся в базе для полнотекстового поиска и для
  механической проверки дословных цитат в статьях следующей фазы.
- Картинки живут ровно одним механизмом — блоками из `attachments`.
  Inline-разметка `![](...)` из тела снимается: смайлы форума (17619
  вхождений) не должны всплыть в заметке, а контентная картинка иначе
  выводилась бы дважды — битой вставкой в тексте и коллаутом ниже.
  ⚠️ ЭТОТ МЕХАНИЗМ ВРЕМЕННЫЙ. Сегодня он ничего не теряет: `local_path`
  пуст у ВСЕХ вложений без исключения, то есть картинок в вики нет ни
  одной — есть только пометки об их отсутствии, и порядок пометок смысла
  не несёт. Как только фаза добора скачает файлы (порядка 900 внешних),
  «все картинки в конец поста» станет настоящей потерей смысла: «вот
  схема, смотри» и сама схема окажутся в разных местах, а в технических
  темах это половина ценности поста. ТРЕБОВАНИЕ К ФАЗЕ 2: вернуть
  позиционный рендеринг — картинка встаёт там, где стояла в тексте, если
  файл есть, и пометкой об отсутствии, если файла нет. Материал для этого
  уже есть: тело хранится и в `markdown`, и в исходном `html`, а
  `attachments` знает URL — позиция сопоставима.
- Хром форума (`attachments.kind == 'chrome'` по единому правилу
  `pipeline.attachments`) не рендерится вовсе — ни вставкой, ни пометкой об
  утрате: терять там нечего, это разметка интерфейса, а не контент поста.
- Всё остальное без файла — коллаут "изображение не сохранилось" с исходным
  URL. Вставка `![[...]]` происходит только когда `local_path` не пуст,
  независимо от значения `status`.
- Один и тот же URL внутри одного поста рендерится один раз (в
  `attachments` строки (mid, url) местами повторяются — это факт разметки,
  таблицу не переписываем, схлопываем при выводе).
- Посты идут `ORDER BY mid` (дефект I3): у постов со `message_*`-снимка
  `page_no` жёстко 1, и сортировка (page_no, mid) всплывала их в начало
  темы — на корпусе это ломало хронологию в 5 темах (26922, 32487, 34559,
  36559, 40626). По `mid` нарушений хронологии нет ни в одной из 3509 тем.
- Темы без единого поста получают заметку с метаданными оглавления и
  коллаутом "содержимое не сохранилось".
- `replies_expected IS NULL` -> "неизвестно" во frontmatter, не 0 и не пусто.
"""
import re
from pathlib import Path

from pipeline import attachments

# Markdown-картинка целиком: `![](url)`. URL может содержать один уровень
# вложенных скобок (`page(1).jpg`) — наивный разбор "до первой ')'" обрезал бы
# адрес и оставлял хвост как текст (та же осторожность, что в html_text).
_IMG_MD = re.compile(r"!\[\]\((?:[^()]|\([^()]*\))*\)")

# Строка, которую Markdown прочтёт как ATX-заголовок, в том числе внутри
# цитаты (`> # ...`). На корпусе таких постов 2.
_ATX_LINE = re.compile(r"^(\s{0,3}(?:>\s?)*)(#{1,6})(\s|$)")

# Setext: строка из дефисов/равно СРАЗУ ПОД строкой текста делает эту строку
# заголовком второго/первого уровня. Подчёркиванием считается и ОДИН символ
# (CommonMark), поэтому `-+`, а не `-{2,}`. На корпусе таких постов 7, два из
# них внутри цитат.
_SETEXT_LINE = re.compile(r"^(\s{0,3}(?:>\s?)*)(-+|=+)\s*$")

_NOTE_NAME = re.compile(r"^Тема (\d+)\.md$")


def _ru_dt(iso: str) -> str:
    """`2007-04-02 12:04:04` -> `02.04.2007 12:04:04`.

    Всё, что не похоже на ISO-дату, возвращается как есть: сейчас
    `parse_thread._dt` отдаёт либо ISO, либо пустую строку, но падать
    `ValueError` на неожиданном значении генератору заметок незачем.
    """
    iso = iso or ""
    m = re.match(r"^(\d{4})-(\d{2})-(\d{2})(.*)$", iso)
    if not m:
        return iso
    y, mo, d, tail = m.groups()
    return "%s.%s.%s%s" % (d, mo, y, tail)


def _escape_wikilink_open(text: str) -> str:
    """Экранирует буквальные `[[` в тексте поста, чтобы Obsidian не принял
    их за открывающую скобку вики-ссылки.

    Найдено проверкой целостности (задача 8, `check_mirror.check`): 18
    постов в 13 темах содержат необработанный BBCode-мусор форума с
    задвоенными квадратными скобками — `[[IMG]url[/img]`, `[[QUOTE]...`,
    `[[/URL [URL=...]]`, `[[url=...]`. Это не наша разметка, а буквальный
    текст исходного поста. Наши собственные вставки `![[local_path]]`
    строятся отдельно (из `attachments`, не из тела) и через эту функцию
    не проходят.
    """
    return text.replace("[[", "\\[\\[")


def _escape_headings(text: str) -> str:
    """Гасит заголовки внутри тела поста.

    Адрес поста — заголовочный якорь, и секция поста кончается на следующем
    заголовке. Значит любой заголовок ВНУТРИ текста поста обрывает сноску:
    `[[Тема N#Пост MID]]` раскроет только начало поста, и опять молча.
    Гасим обе формы, которыми Markdown делает заголовок:

    - ATX (`# текст`) — экранируем первую решётку, `\\#` рендерится как
      обычная решётка;
    - setext (строка из `---`/`===` сразу под строкой текста) — экранируем
      первый символ; `\\-` рендерится как дефис, а строка перестаёт быть
      подчёркиванием заголовка. Строку без текста над ней трогать не нужно:
      это просто горизонтальная черта, она безвредна.

    Обе формы учитывают префикс цитаты `> `: 2 из 7 setext-строк корпуса
    сидят внутри цитат.
    """
    lines = text.split("\n")
    out = []
    for i, line in enumerate(lines):
        m = _ATX_LINE.match(line)
        if m:
            out.append("%s\\%s%s" % (m.group(1), m.group(2), line[m.end(2):]))
            continue
        m = _SETEXT_LINE.match(line)
        if m and i > 0 and lines[i - 1].strip():
            out.append("%s\\%s" % (m.group(1), line[m.end(1):]))
            continue
        out.append(line)
    return "\n".join(out)


def _body(markdown: str) -> str:
    """Тело поста для заметки: markdown из базы без inline-картинок и без
    того, что Obsidian прочитал бы не как текст поста.
    """
    text = _IMG_MD.sub("", markdown or "")
    text = _escape_wikilink_open(text)
    text = _escape_headings(text)
    # После вырезания картинок остаются висячие пробелы и пустые строки.
    text = re.sub(r"[ \t]+\n", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def _yaml_dquote(s: str) -> str:
    """Заворачивает строку в YAML double-quoted scalar с полным
    экранированием — можно вставлять как значение фронтматтера, каким бы
    ни было содержимое (кавычки, обратный слэш, двоеточие, ведущие `!`/`[`/`|`,
    которые вне кавычек YAML трактует как тег/список/блочный скаляр).

    Порядок экранирования важен: сначала `\\`, потом `"` — иначе `"` внутри
    исходной строки задвоится через свежедобавленный `\\`.
    """
    s = (s or "").replace("\\", "\\\\").replace('"', '\\"')
    return '"%s"' % s


def render_thread(conn, tid: int) -> str:
    row = conn.execute(
        "SELECT t.tid, t.fid, t.title, t.author, t.started_at, t.replies_expected, t.views, "
        "COALESCE(s.title, '') FROM threads t LEFT JOIN sections s ON s.fid = t.fid WHERE t.tid = ?",
        (tid,)).fetchone()
    if row is None:
        raise KeyError(tid)
    tid, fid, title, author, started, replies, views, section = row

    replies_str = "неизвестно" if replies is None else str(replies)
    display_title = title or "Тема %d" % tid
    out = ["---",
           "tid: %d" % tid,
           "fid: %d" % fid,
           "раздел: %s" % _yaml_dquote(section),
           "aliases: [%s]" % _yaml_dquote(display_title),
           "автор: %s" % _yaml_dquote(author or ""),
           "начата: %s" % (started or ""),
           "ответов: %s" % replies_str,
           "просмотров: %s" % (views if views is not None else ""),
           "---", "", "# %s" % display_title, ""]

    # ORDER BY mid, без page_no: см. docstring модуля (дефект I3).
    posts = conn.execute(
        "SELECT mid, author, posted_at, number, markdown FROM posts WHERE tid = ? ORDER BY mid",
        (tid,)).fetchall()

    if not posts:
        out.append("> [!missing] содержимое не сохранилось")
        out.append("")
        return "\n".join(out)

    for mid, p_author, posted_at, number, markdown in posts:
        # Заголовок — он же якорь: `[[Тема <TID>#Пост <MID>]]`.
        out.append("##### Пост %d" % mid)
        out.append("")
        meta = " · ".join(x for x in (p_author or "аноним", _ru_dt(posted_at or ""), number or "") if x)
        out.append("*%s*" % meta)
        out.append("")

        body = _body(markdown)
        if body:
            out.append(body)
            out.append("")

        # Дедуп по URL: attachments местами содержит дублирующиеся строки
        # (mid, url) — один и тот же URL не должен давать два одинаковых
        # блока подряд. Если среди дублей есть строка с заполненным
        # local_path, она побеждает (реальная вставка важнее пометки).
        by_url = {}
        order = []
        for a_kind, a_url, a_local in conn.execute(
                "SELECT kind, url, local_path FROM attachments WHERE mid = ?", (mid,)):
            if not attachments.is_content(a_kind):
                continue
            key = a_url or ""
            if key not in by_url:
                order.append(key)
                by_url[key] = (a_local, a_url)
            elif a_local and not by_url[key][0]:
                by_url[key] = (a_local, a_url)

        for key in order:
            a_local, a_url = by_url[key]
            if a_local:
                # Вставка файла только когда local_path реально заполнен —
                # status сам по себе ничего не гарантирует.
                out.append("![[%s]]" % a_local)
            else:
                out.append("> [!missing] изображение не сохранилось\n> %s" % (a_url or ""))
            out.append("")

    return "\n".join(out)


def write_all(conn, out_dir: Path) -> int:
    """Пишет заметку на каждую тему базы и убирает заметки исчезнувших тем.

    Удаляются только файлы вида `Тема <TID>.md`, чей `tid` в базе больше не
    встречается: имя заметки детерминировано генератором, поэтому лишний
    файл виден точно. Чужие файлы (статьи следующей фазы, заметки Сергея)
    в каталоге не трогаются.

    ПРЕДОХРАНИТЕЛЬ: удалений не может быть больше, чем записей. Уборка
    мусора — это единицы файлов на фоне тысяч записанных; «удалить больше,
    чем записали» означает не мусор, а то, что БАЗА НЕ ОПИСЫВАЕТ ЭТО
    ЗЕРКАЛО: пустая база (забыли загрузку), чужая или маленькая база
    (опечатка в `--db`). Раньше такой прогон молча сносил все 6338 заметок
    и рапортовал об успехе («заметок: 0», код возврата 0). Теперь заметки
    остаются нетронутыми, а вызывающий получает `RuntimeError` с цифрами.
    """
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    tids = set()
    n = 0
    for (tid,) in conn.execute("SELECT tid FROM threads ORDER BY tid"):
        (out_dir / ("Тема %d.md" % tid)).write_text(render_thread(conn, tid), encoding="utf-8")
        tids.add(tid)
        n += 1
    stale = [p for p in sorted(out_dir.glob("Тема *.md"))
             if _NOTE_NAME.match(p.name) and int(_NOTE_NAME.match(p.name).group(1)) not in tids]
    if len(stale) > n:
        raise RuntimeError(
            "отказ убирать заметки: записано %d, под удаление попало %d. "
            "Похоже, база не описывает это зеркало (пустая база, не тот --db "
            "или пропущенный шаг загрузки). Зеркало не тронуто: %s"
            % (n, len(stale), out_dir))
    for path in stale:
        path.unlink()
    return n
